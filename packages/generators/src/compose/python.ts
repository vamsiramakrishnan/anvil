const MAIN = `"""python -m anvil_compose: read, check, plan, or run a flow document.

    python -m anvil_compose connectors
    python -m anvil_compose operations [CONNECTOR]
    python -m anvil_compose validate FLOW.json
    python -m anvil_compose plan FLOW.json [--mermaid]
    python -m anvil_compose run FLOW.json [--dry-run]

Every command prints JSON on stdout. 'validate' exits 1 on an error finding;
'run' exits 1 when the run did not succeed.
"""

import json
import sys

from . import ComposeError, Composite


def main(argv=None) -> int:
    args = list(sys.argv[1:] if argv is None else argv)
    if not args or args[0] in ("-h", "--help"):
        print(__doc__.strip())
        return 0
    command, rest = args[0], args[1:]
    composite = Composite()
    try:
        if command == "connectors":
            print(json.dumps(composite.connectors()))
            return 0
        if command == "operations":
            print(json.dumps(composite.operations(rest[0] if rest else None), indent=2))
            return 0
        if command in ("validate", "plan", "run") and rest:
            flow = composite.load(rest[0])
            if command == "validate":
                findings = flow.validate()
                print(json.dumps(findings, indent=2))
                return 1 if any(f["level"] == "error" for f in findings) else 0
            if command == "plan":
                print(flow.mermaid() if "--mermaid" in rest else json.dumps(flow.plan(), indent=2))
                return 0
            result = flow.dry_run() if "--dry-run" in rest else flow.run()
            print(json.dumps(result.to_json(), indent=2, default=str))
            return 0 if result.ok else 1
    except ComposeError as error:
        print(json.dumps({"error": error.to_dict()}), file=sys.stderr)
        return 2
    print("usage: python -m anvil_compose connectors|operations|validate|plan|run ...", file=sys.stderr)
    return 2


if __name__ == "__main__":
    sys.exit(main())
`;

