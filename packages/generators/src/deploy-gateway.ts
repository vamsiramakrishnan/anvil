/**
 * The fleet gateway on Cloud Run (Branchyard's "Anvil contract v2", item 5).
 *
 * `generateGatewayCloudRun` renders the files an operator reviews and applies:
 * a Dockerfile whose entrypoint is `anvil serve mcp <bundles> --fleet --http
 * "$PORT" --host 0.0.0.0` and a Cloud Run service (`gcloud run services replace`
 * format) that carries the health probes, the inbound `branchyard` JWKS
 * configuration, the Firestore idempotency ledger, and the SIGTERM drain window.
 * It is configuration only: the listener verifies tokens with the code that
 * already exists (`inbound-auth.ts`). Nothing here calls Google Cloud.
 */

/** Where the files land, relative to the output directory. */
export const GATEWAY_DEPLOY_PREFIX = "deploy/gateway/";

/** Seconds the listener drains in-flight calls on SIGTERM; under Cloud Run's 10-second default. */
export const GATEWAY_SHUTDOWN_GRACE_SECONDS = 8;

export interface GatewayCloudRunOptions {
  /** Cloud Run service name. Default `anvil-gateway`. */
  serviceName?: string;
  /** Container image reference built from the generated Dockerfile. */
  image: string;
  /** GCP project id, for the ledger URI. */
  project: string;
  /** The gateway's public https URL (custom domain or the run.app URL), no path. */
  publicUrl: string;
  /** The Branchyard server's https URL: the token issuer. */
  branchyardUrl: string;
  /** Override the JWKS URL. Default `<branchyardUrl>/.well-known/jwks.json`. */
  jwksUri?: string;
  /** Firestore database for the ledger. Default `(default)`. */
  ledgerDatabase?: string;
  /** Ledger namespace. Default `gateway`. */
  ledgerNamespace?: string;
  /** `ANVIL_ENV`. Default `prod`. */
  env?: string;
  /** Secret Manager secret holding the vault key file. Default `anvil-vault-key`. */
  vaultKeySecret?: string;
}

function httpsOrigin(label: string, value: string): URL {
  let url: URL;
  try {
    url = new URL(value);
  } catch {
    throw new Error(`${label} must be an https URL`);
  }
  if (url.protocol !== "https:" || url.username || url.password || url.search || url.hash) {
    throw new Error(`${label} must be an https URL without credentials, query, or fragment`);
  }
  return url;
}

const SAFE = /^[A-Za-z0-9._()-]+$/;

function safeName(label: string, value: string): string {
  if (!SAFE.test(value)) throw new Error(`${label} has characters a Cloud Run name cannot carry`);
  return value;
}

/** The `deploy/gateway/*` files, keyed by path. Throws on an unusable option. */
export function generateGatewayCloudRun(options: GatewayCloudRunOptions): Record<string, string> {
  const publicUrl = httpsOrigin("publicUrl", options.publicUrl);
  const issuer = httpsOrigin("branchyardUrl", options.branchyardUrl);
  const publicBase = publicUrl.origin + publicUrl.pathname.replace(/\/+$/, "");
  const issuerBase = issuer.origin + issuer.pathname.replace(/\/+$/, "");
  const jwks = options.jwksUri
    ? httpsOrigin("jwksUri", options.jwksUri).toString()
    : `${issuerBase}/.well-known/jwks.json`;
  const name = safeName("serviceName", options.serviceName ?? "anvil-gateway");
  const project = safeName("project", options.project);
  const database = safeName("ledgerDatabase", options.ledgerDatabase ?? "(default)");
  const namespace = safeName("ledgerNamespace", options.ledgerNamespace ?? "gateway");
  const secret = safeName("vaultKeySecret", options.vaultKeySecret ?? "anvil-vault-key");
  if (!options.image.trim() || /\s/.test(options.image)) {
    throw new Error("image must be a container image reference");
  }
  const env: Array<[string, string]> = [
    ["ANVIL_ENV", options.env ?? "prod"],
    ["ANVIL_INBOUND_AUTH_MODE", "branchyard"],
    ["ANVIL_INBOUND_ISSUER", issuerBase],
    ["ANVIL_INBOUND_AUDIENCE", `${publicBase}/mcp`],
    ["ANVIL_INBOUND_JWKS_URI", jwks],
    ["ANVIL_GATEWAY_PUBLIC_URL", publicBase],
    ["ANVIL_LEDGER", `firestore://${project}/${database}/${namespace}`],
    ["ANVIL_SHUTDOWN_GRACE_SECONDS", String(GATEWAY_SHUTDOWN_GRACE_SECONDS)],
    ["ANVIL_VAULT_KEY_FILE", "/secrets/vault/key"],
    ["ANVIL_VAULT_DIR", "/tmp/anvil-vault"],
  ];
  const envYaml = env
    .map(
      ([key, value]) => `            - name: ${key}\n              value: ${JSON.stringify(value)}`,
    )
    .join("\n");
  const service = `# Generated by \`anvil deploy gateway\`. Apply with:
#   gcloud run services replace service.yaml --region <region> --project ${project}
# Review before applying; Anvil never calls Google Cloud.
apiVersion: serving.knative.dev/v1
kind: Service
metadata:
  name: ${name}
spec:
  template:
    metadata:
      annotations:
        # Cloud Run sends SIGTERM and allows 10 seconds; the listener drains for
        # ANVIL_SHUTDOWN_GRACE_SECONDS (${GATEWAY_SHUTDOWN_GRACE_SECONDS}) and exits 0.
        run.googleapis.com/startup-cpu-boost: "true"
    spec:
      timeoutSeconds: 300
      containers:
        - image: ${options.image}
          ports:
            - containerPort: 8080
          resources:
            limits:
              cpu: "1"
              memory: 512Mi
          startupProbe:
            httpGet:
              path: /readyz
              port: 8080
            periodSeconds: 5
            timeoutSeconds: 3
            failureThreshold: 12
          livenessProbe:
            httpGet:
              path: /healthz
              port: 8080
            periodSeconds: 30
            timeoutSeconds: 3
            failureThreshold: 3
          env:
${envYaml}
          volumeMounts:
            - name: vault-key
              mountPath: /secrets/vault
      volumes:
        - name: vault-key
          secret:
            secretName: ${secret}
            items:
              - key: latest
                path: key
`;
  const dockerfile = `# Generated by \`anvil deploy gateway\`.
# Build context layout:
#   anvil/     a prebuilt Anvil CLI tree (bin-anvil.js and its node_modules)
#   bundles/   the reviewed, certified bundles the gateway serves
# The image performs no registry access or dependency resolution.
FROM node:22-slim
WORKDIR /app
ENV NODE_ENV=production
COPY anvil /opt/anvil
COPY bundles /srv/bundles
EXPOSE 8080
USER node
# exec: node is PID 1's replacement and receives Cloud Run's SIGTERM directly.
CMD ["sh", "-c", "exec node /opt/anvil/dist/bin-anvil.js serve mcp /srv/bundles --fleet --http \\"$PORT\\" --host 0.0.0.0"]
`;
  return {
    [`${GATEWAY_DEPLOY_PREFIX}Dockerfile`]: dockerfile,
    [`${GATEWAY_DEPLOY_PREFIX}service.yaml`]: service,
  };
}
