/** The generated `mcp/server.js` entrypoint that boots the server over stdio. */
export function generateMcpServerSource(air: AirDocument): string {
  return `#!/usr/bin/env node
// Generated by Anvil for service "${air.service.id}". Do not edit by hand —
// regenerate from AIR (\`anvil compile\`). One tool per approved operation.
import { readFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { StdioServerTransport } from "@modelcontextprotocol/sdk/server/stdio.js";
import { buildMcpServer } from "@anvil/mcp-runtime";
import {
  allowedHostsFor,
  FetchTransport,
  InMemoryObserver,
  loadRuntimeConfig,
  resolveCredentials,
  resolveLedger,
} from "@anvil/runtime";
import { loadAirDocument } from "@anvil/air";

const air = loadAirDocument(
  JSON.parse(readFileSync(fileURLToPath(new URL("./air.json", import.meta.url)), "utf8")),
);
const resources = JSON.parse(
  readFileSync(fileURLToPath(new URL("./resources.json", import.meta.url)), "utf8"),
);
const config = loadRuntimeConfig();
const transport = new FetchTransport();
const credentials = resolveCredentials(config);
const ledger = resolveLedger(config.ledger, {
  resultTtlMs: config.ledgerResultTtlSeconds * 1000,
});
const observer = new InMemoryObserver();

// ANVIL_BASE_URL is a deliberate operator override (loopback self-test, staging
// smoke tests); when set without an explicit allowlist, egress pins to its host.
const baseUrl = process.env.ANVIL_BASE_URL ?? air.service.servers[0]?.url ?? "";
const allowedHosts = allowedHostsFor(
  config.allowedHosts,
  baseUrl,
  process.env.ANVIL_BASE_URL !== undefined,
);
// A non-HTTP/JSON source (SOAP, GraphQL, gRPC, an adopted MCP tool) reaches the
// runtime with a coordinate Anvil synthesized. Set ANVIL_PROTOCOL_FACADE to the
// reason ANVIL_BASE_URL really does serve those coordinates over HTTP+JSON; the
// runtime refuses those operations otherwise, and records this reason when it
// does not. It is a declaration, never an inference.
const protocolFacade = process.env.ANVIL_PROTOCOL_FACADE;
const server = buildMcpServer(air, {
  resources,
  contextFor: () => ({
    transport,
    serviceId: air.service.id,
    credentials,
    ledger,
    observer,
    baseUrl,
    authProfile: config.authProfile,
    allowedHosts,
    protocolFacade,
    env: config.env,
    timeoutMs: config.upstreamTimeoutMs,
  }),
});

await server.connect(new StdioServerTransport());
`;
}

/**
 * The generated `mcp/server-sse.js` entrypoint: the REMOTE MCP server, spoken
 * over HTTP + Server-Sent Events. This is the companion to the stdio server —
 * same tools, same safety runtime — for clients that connect to a URL instead of
 * spawning a local process. It exposes `GET /sse` (the event stream) and
 * `POST /messages?sessionId=…` (client → server), the MCP HTTP+SSE transport.
 *
 * Unlike `runtime/server.js` (stateless StreamableHTTP for Cloud Run), SSE is
 * stateful — one open stream per session — so a horizontally-scaled deployment
 * needs sticky routing by `sessionId`. The safety hot path is identical: one tool
 * per approved operation, egress pinned to the allowlist, secrets from the env.
 */
export function generateMcpSseServerSource(air: AirDocument): string {
  const requiresDurableLedger = air.operations.some(
    (operation) =>
      operation.state === "approved" &&
      operation.effect.kind === "mutation" &&
      operation.idempotency.mode === "required",
  );
  return `#!/usr/bin/env node
// Generated by Anvil for service "${air.service.id}" — REMOTE MCP server (HTTP + SSE).
// Do not edit by hand — regenerate from AIR (\`anvil compile\`).
// Transport: GET /sse (event stream) + POST /messages?sessionId=… (client→server).
import { createServer } from "node:http";
import { readFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { SSEServerTransport } from "@modelcontextprotocol/sdk/server/sse.js";
import {
  buildMcpServer,
  loadInboundAuthConfig,
  protectedResourceMetadata,
  verifyInboundToken,
} from "@anvil/mcp-runtime";
import {
  allowedHostsFor,
  currentInboundIdentity,
  FetchTransport,
  InMemoryObserver,
  loadRuntimeConfig,
  probeLedgerReadiness,
  resolveCredentials,
  resolveLedger,
  withInboundIdentity,
} from "@anvil/runtime";
import { loadAirDocument } from "@anvil/air";

const air = loadAirDocument(
  JSON.parse(readFileSync(fileURLToPath(new URL("./air.json", import.meta.url)), "utf8")),
);
const resources = JSON.parse(
  readFileSync(fileURLToPath(new URL("./resources.json", import.meta.url)), "utf8"),
);
const config = loadRuntimeConfig();
const deps = {
  transport: new FetchTransport(),
  credentials: resolveCredentials(config),
  ledger: resolveLedger(config.ledger, {
    resultTtlMs: config.ledgerResultTtlSeconds * 1000,
  }),
  observer: new InMemoryObserver(),
};
const baseUrl = process.env.ANVIL_BASE_URL ?? air.service.servers[0]?.url ?? "";
const allowedHosts = allowedHostsFor(
  config.allowedHosts,
  baseUrl,
  process.env.ANVIL_BASE_URL !== undefined,
);
// A non-HTTP/JSON source (SOAP, GraphQL, gRPC, an adopted MCP tool) reaches the
// runtime with a coordinate Anvil synthesized. Set ANVIL_PROTOCOL_FACADE to the
// reason ANVIL_BASE_URL really does serve those coordinates over HTTP+JSON; the
// runtime refuses those operations otherwise, and records this reason when it
// does not. It is a declaration, never an inference.
const protocolFacade = process.env.ANVIL_PROTOCOL_FACADE;
const mcpContext = () => ({
  ...deps,
  serviceId: air.service.id,
  baseUrl,
  authProfile: config.authProfile,
  allowedHosts,
  protocolFacade,
  env: config.env,
  timeoutMs: config.upstreamTimeoutMs,
  // The per-request caller identity (set by withInboundIdentity around dispatch);
  // the credential resolver uses it as the subject_token for OBO exchange.
  inbound: currentInboundIdentity(),
});

// Inbound authentication: this server is an OAuth 2 resource server, exactly
// like runtime/server.js. Mode "none" (the default) admits everything, for
// local runs behind other controls — but every deployed transport validates
// the same way, so a client cannot bypass ANVIL_INBOUND_AUTH by using SSE.
const inboundAuth = loadInboundAuthConfig();
const resourceMetadata = protectedResourceMetadata(inboundAuth);

async function authorized(req, res) {
  const header = req.headers["authorization"];
  const result = await verifyInboundToken(header, inboundAuth);
  if (!result.ok) {
    res.writeHead(result.status, {
      "content-type": "application/json",
      "www-authenticate": result.wwwAuthenticate,
    });
    res.end(JSON.stringify({ error: { code: result.error, message: result.description } }));
    return { ok: false };
  }
  const rawToken =
    typeof header === "string" ? header.replace(/^Bearer\\s+/i, "").trim() : undefined;
  if (inboundAuth.mode !== "none" && !rawToken) {
    res.writeHead(401, {
      "content-type": "application/json",
      "www-authenticate": 'Bearer error="invalid_token"',
    });
    res.end(
      JSON.stringify({
        error: { code: "invalid_token", message: "Verified bearer token is unavailable." },
      }),
    );
    return { ok: false };
  }
  // Inbound mode "none" deliberately performs no token verification. Never promote a
  // caller-supplied bearer from that mode into a "validated" OBO subject.
  return {
    ok: true,
    identity:
      inboundAuth.mode === "none" ? undefined : inboundIdentityFrom(rawToken, result.claims),
  };
}

// The raw caller token + its verified claims → the OBO subject. The raw bearer is
// forwarded ONLY to the configured token endpoint for exchange; it is never sent
// to the upstream directly, recorded, or logged.
function inboundIdentityFrom(raw, claims) {
  if (!raw) return undefined;
  return {
    subjectToken: raw,
    subjectTokenType: raw.split(".").length === 3 ? "jwt" : "access_token",
    sub: claims.sub,
    email: claims.email,
    scope: claims.scope,
    claims,
  };
}

// One live SSE transport per session, keyed by its sessionId. POST /messages
// carries ?sessionId=… back to the stream that owns the conversation.
const sessions = new Map();

function send(res, status, body) {
  res.writeHead(status, { "content-type": "application/json" });
  res.end(JSON.stringify(body));
}

const server = createServer(async (req, res) => {
  const url = new URL(req.url ?? "/", "http://localhost");
  if (url.pathname === "/healthz") return send(res, 200, { status: "ok" });
  if (url.pathname === "/readyz") {
    const ledger = await probeLedgerReadiness(
      deps.ledger,
      ${requiresDurableLedger} && config.env !== "dev",
    );
    return ledger.ready
      ? send(res, 200, { ready: true, service: air.service.id })
      : send(res, 503, {
          ready: false,
          service: air.service.id,
          code: "ledger_unavailable",
        });
  }
  if (url.pathname === "/.well-known/oauth-protected-resource") {
    return resourceMetadata
      ? send(res, 200, resourceMetadata)
      : send(res, 404, { error: { code: "not_found", message: "Inbound auth is not configured." } });
  }
  if (req.method === "GET" && url.pathname === "/sse") {
    const auth = await authorized(req, res);
    if (!auth.ok) return;
    const transport = new SSEServerTransport("/messages", res);
    sessions.set(transport.sessionId, { transport, identity: auth.identity });
    res.on("close", () => sessions.delete(transport.sessionId));
    const mcp = buildMcpServer(air, { resources, contextFor: () => mcpContext() });
    return auth.identity
      ? withInboundIdentity(auth.identity, () => mcp.connect(transport))
      : mcp.connect(transport);
  }
  if (req.method === "POST" && url.pathname === "/messages") {
    const auth = await authorized(req, res);
    if (!auth.ok) return;
    const sessionId = url.searchParams.get("sessionId");
    const entry = sessionId ? sessions.get(sessionId) : undefined;
    if (!entry)
      return send(res, 400, {
        error: { code: "no_session", message: "Unknown or missing sessionId. Open GET /sse first." },
      });
    return entry.identity
      ? withInboundIdentity(entry.identity, () => entry.transport.handlePostMessage(req, res))
      : entry.transport.handlePostMessage(req, res);
  }
  return send(res, 404, {
    error: { code: "not_found", message: "MCP over SSE: GET /sse, then POST /messages?sessionId=…" },
  });
});

server.listen(process.env.PORT ?? 8080, () =>
  console.error(air.service.id, "MCP SSE listening on /sse"),
);
`;
}
