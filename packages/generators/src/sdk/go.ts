/**
 * The Go SDK — a zero-dependency module over `net/http`.
 *
 * Same split as every other language Anvil emits: `safety.go` and `invoke.go`
 * are the reviewed decision core, identical for every service, and generation
 * only adds rows to the operation table they read.
 */
export function generateGoSdk(plan: SdkPlan): Record<string, string> {
  const root = "sdk/go";
  return {
    [`${root}/go.mod`]: goMod(plan),
    [`${root}/README.md`]: readme(plan),
    [`${root}/errors.go`]: errorsFile(plan),
    [`${root}/safety.go`]: safetyFile(plan),
    [`${root}/spec.go`]: specFile(plan),
    [`${root}/operations.go`]: operationsFile(plan),
    [`${root}/invoke.go`]: invokeFile(plan),
    [`${root}/dryrun.go`]: goDryRunFile(goPackage(plan)),
    // mTLS and the OAuth grants are emitted only for the service that
    // declared the scheme — a bearer/api-key service never carries
    // crypto/tls plumbing or dead token-endpoint code.
    ...(plan.auth.tls ? { [`${root}/mtls.go`]: mtlsFile(plan) } : {}),
    ...(needsOauth(plan)
      ? { [`${root}/oauth.go`]: oauthFile(goPackage(plan), oauthGrantsOf(plan)) }
      : {}),
    [`${root}/client.go`]: clientFile(plan),
    // Always emitted, unlike the TypeScript one: `OperationSpec.Soap` is a
    // typed field, so `SoapBinding` has to exist even in a REST service. Go
    // permits unused package-level functions, so the cost is a file nothing
    // calls rather than a compile error.
    [`${root}/soap.go`]: `// Generated by Anvil. Do not edit — regenerate from AIR.\npackage ${goPackage(plan)}\n\nimport (\n\t"encoding/xml"\n\t"errors"\n\t"fmt"\n\t"sort"\n\t"strings"\n)\n${GO_SOAP}`,
  };
}

const g = (value: unknown): string => JSON.stringify(value);

function goPascal(source: string): string {
  return source
    .split(/[^a-zA-Z0-9]+/)
    .filter(Boolean)
    .map((word) => word.charAt(0).toUpperCase() + word.slice(1))
    .join("");
}

function goType(field: SdkField): string {
  const base = (() => {
    switch (field.type) {
      case "string":
        return "string";
      case "integer":
        return "int64";
      case "number":
        return "float64";
      case "boolean":
        return "bool";
      case "array":
        return "[]any";
      case "object":
        return "map[string]any";
      default:
        return "any";
    }
  })();
  if (field.required) return base;
  // Slices, maps, and `any` already carry a nil that means "absent"; scalars do
  // not, so an optional scalar is a pointer rather than a zero value the wire
  // could not distinguish from an omission.
  return base === "string" || base === "int64" || base === "float64" || base === "bool"
    ? `*${base}`
    : base;
}

function isPointer(field: SdkField): boolean {
  return goType(field).startsWith("*");
}

function goMod(plan: SdkPlan): string {
  return `// Generated by Anvil. Do not edit — regenerate from AIR.
module github.com/anvil-sdk/${plan.service.id}

go 1.21
`;
}

function readme(plan: SdkPlan): string {
  const pkg = goPackage(plan);
  const first = plan.operations[0];
  const required = first ? first.params.filter((param) => param.required) : [];
  const usage = first
    ? [
        "```go",
        `client, err := ${pkg}.New()`,
        "if err != nil {",
        "\tlog.Fatal(err)",
        "}",
        `result, err := client.${first.names.pascal}(ctx, ${pkg}.${first.names.pascal}Input{`,
        ...required.map((param) => `\t${goPascal(param.key)}: "…",`),
        `}${
          first.confirmation.required || first.idempotency.callerKeyRequired
            ? `, ${pkg}.CallOptions{${first.confirmation.required ? "Confirm: true" : ""}${
                first.confirmation.required && first.idempotency.callerKeyRequired ? ", " : ""
              }${first.idempotency.callerKeyRequired ? 'IdempotencyKey: "order-1234"' : ""}}`
            : ""
        })`,
        "```",
      ].join("\n")
    : "_This bundle has no approved operations yet._";
  return `# ${plan.service.displayName} — Go SDK

${plan.service.description}

Generated by Anvil from AIR. Zero dependencies — \`net/http\` and \`encoding/json\`
from the standard library, so \`sdk/go/\` can be vendored directly.

${usage}

The credential is read from \`${plan.auth.envVar}\` when \`New\` is called without
\`WithToken\`. It is never logged, echoed, or included in an error.

Safety is not advisory: an operation that requires confirmation returns
\`*Error\` with \`Code == "confirmation_required"\` before anything reaches the
network, and a transient failure on a mutation that cannot prove idempotence
returns \`"unsafe_retry_blocked"\` rather than being sent twice.

Every call can be previewed: set \`CallOptions{DryRun: true}\` and the same
gates run, then a redacted request plan (\`map[string]any\`) comes back
instead of a response — nothing is sent and no credential is resolved. It is
the plan \`anvil run --dry-run\` prints.

See \`../README.md\` for the full cross-language contract.
`;
}

