function goInputStruct(op: SdkOperation): string {
  const fields: string[] = [];
  const assignments: string[] = [];
  const push = (field: SdkField, source: string) => {
    const name = goPascal(field.key);
    const doc = field.description ? `\t// ${field.description}\n` : "";
    fields.push(`${doc}\t${name} ${goType(field)} \`json:${g(`${field.key},omitempty`)}\``);
    if (field.required) {
      assignments.push(`\tpayload[${g(field.key)}] = in.${name}`);
    } else if (isPointer(field)) {
      assignments.push(`\tif in.${name} != nil {\n\t\tpayload[${g(field.key)}] = *in.${name}\n\t}`);
    } else {
      assignments.push(`\tif in.${name} != nil {\n\t\tpayload[${g(field.key)}] = in.${name}\n\t}`);
    }
    void source;
  };
  for (const param of op.params) push(param, param.in);
  if (op.body?.projection === "fields") {
    for (const field of op.body.fields) push(field, "body");
  } else if (op.body) {
    push(
      {
        wireName: "body",
        key: "body",
        required: op.body.required,
        type: "any",
        description: `The request body, sent verbatim (content type ${op.body.contentType}).`,
      },
      "body",
    );
  }
  return `// ${op.names.pascal}Input is the input for ${op.canonicalName}.
type ${op.names.pascal}Input struct {
${fields.length > 0 ? fields.join("\n") : "\t// This operation takes no input."}
}

func (in ${op.names.pascal}Input) payload() map[string]any {
	payload := map[string]any{}
${assignments.join("\n")}
	return payload
}`;
}

function goMethod(op: SdkOperation): string {
  const doc = [`// ${op.names.pascal} — ${op.description}`, "//"]
    .concat(safetyNotes(op).flatMap((note) => wrap(note, 72).map((line) => `// ${line}`)))
    .join("\n");
  const lines = [
    doc,
    `func (c *Client) ${op.names.pascal}(ctx context.Context, in ${op.names.pascal}Input, options ...CallOptions) (any, error) {`,
    `\treturn invoke(ctx, c.config, Operations[${g(op.names.pascal)}], in.payload(), firstCallOptions(options))`,
    "}",
  ];

  const pager = op.pager;
  if (pager) {
    lines.push("", goPager(op, pager));
  }

  const contract = op.async;
  if (contract?.statusMethodBase && contract.statusJobIdKey && contract.terminalStates.length > 0) {
    const statusPascal = goPascal(contract.statusMethodBase);
    const statusJobIdKey = contract.statusJobIdKey;
    lines.push(
      "",
      `// WaitFor${op.names.pascal} — ${contract.instruction}`,
      "//",
      "// It polls at the interval the contract declares and returns the first status",
      "// response in a terminal state. Every field name below is the one AIR",
      "// resolved — none is guessed.",
      `func (c *Client) WaitFor${op.names.pascal}(ctx context.Context, submitResult any, timeout time.Duration) (any, error) {
	handle, ok := field(submitResult, ${g(contract.jobIdField)}).(string)
	if !ok || handle == "" {
		return nil, &Error{Code: "schema_mismatch", Operation: ${g(op.id)}, Message: "The submit response carried no ${contract.jobIdField} to poll on."}
	}
	if timeout <= 0 {
		timeout = ${contract.pollIntervalSeconds * 60} * time.Second
	}
	deadline := time.Now().Add(timeout)
	terminal := map[string]bool{${contract.terminalStates.map((state) => `${g(state)}: true`).join(", ")}}
	for {
		status, err := c.${statusPascal}(ctx, ${statusPascal}Input{${goPascal(statusJobIdKey)}: handle})
		if err != nil {
			return nil, err
		}
		if state, isString := field(status, ${g(contract.stateField ?? "state")}).(string); isString && terminal[state] {
			return status, nil
		}
		if time.Now().After(deadline) {
			return nil, &Error{Code: "upstream_timeout", Operation: ${g(op.id)}, Message: "${op.canonicalName} did not reach a terminal state before the wait deadline.", Retryable: true}
		}
		if err := sleepFor(ctx, ${contract.pollIntervalSeconds * 1000}, c.config.sleep); err != nil {
			return nil, err
		}
	}
}`,
    );
  }
  return lines.join("\n");
}
