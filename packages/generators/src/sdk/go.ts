import { errorsFile, goPackage, specFile } from "./go-core.js";
import { invokeFile, safetyFile } from "./go-invoke.js";
import type { SdkField, SdkOperation, SdkPlan } from "./plan.js";
import { safetyNotes, wrap } from "./shared.js";
import { GO_SOAP } from "./soap.js";

/**
 * The Go SDK — a zero-dependency module over `net/http`.
 *
 * Same split as every other language Anvil emits: `safety.go` and `invoke.go`
 * are the reviewed decision core, identical for every service, and generation
 * only adds rows to the operation table they read.
 */
export function generateGoSdk(plan: SdkPlan): Record<string, string> {
  const root = "sdk/go";
  return {
    [`${root}/go.mod`]: goMod(plan),
    [`${root}/README.md`]: readme(plan),
    [`${root}/errors.go`]: errorsFile(plan),
    [`${root}/safety.go`]: safetyFile(plan),
    [`${root}/spec.go`]: specFile(plan),
    [`${root}/operations.go`]: operationsFile(plan),
    [`${root}/invoke.go`]: invokeFile(plan),
    [`${root}/client.go`]: clientFile(plan),
    // Always emitted, unlike the TypeScript one: `OperationSpec.Soap` is a
    // typed field, so `SoapBinding` has to exist even in a REST service. Go
    // permits unused package-level functions, so the cost is a file nothing
    // calls rather than a compile error.
    [`${root}/soap.go`]: `// Generated by Anvil. Do not edit — regenerate from AIR.\npackage ${goPackage(plan)}\n\nimport (\n\t"encoding/xml"\n\t"errors"\n\t"fmt"\n\t"sort"\n\t"strings"\n)\n${GO_SOAP}`,
  };
}

const g = (value: unknown): string => JSON.stringify(value);

function goPascal(source: string): string {
  return source
    .split(/[^a-zA-Z0-9]+/)
    .filter(Boolean)
    .map((word) => word.charAt(0).toUpperCase() + word.slice(1))
    .join("");
}

function goType(field: SdkField): string {
  const base = (() => {
    switch (field.type) {
      case "string":
        return "string";
      case "integer":
        return "int64";
      case "number":
        return "float64";
      case "boolean":
        return "bool";
      case "array":
        return "[]any";
      case "object":
        return "map[string]any";
      default:
        return "any";
    }
  })();
  if (field.required) return base;
  // Slices, maps, and `any` already carry a nil that means "absent"; scalars do
  // not, so an optional scalar is a pointer rather than a zero value the wire
  // could not distinguish from an omission.
  return base === "string" || base === "int64" || base === "float64" || base === "bool"
    ? `*${base}`
    : base;
}

function isPointer(field: SdkField): boolean {
  return goType(field).startsWith("*");
}

function goMod(plan: SdkPlan): string {
  return `// Generated by Anvil. Do not edit — regenerate from AIR.
module github.com/anvil-sdk/${plan.service.id}

go 1.21
`;
}

function readme(plan: SdkPlan): string {
  const pkg = goPackage(plan);
  const first = plan.operations[0];
  const required = first ? first.params.filter((param) => param.required) : [];
  const usage = first
    ? [
        "```go",
        `client, err := ${pkg}.New()`,
        "if err != nil {",
        "\tlog.Fatal(err)",
        "}",
        `result, err := client.${first.names.pascal}(ctx, ${pkg}.${first.names.pascal}Input{`,
        ...required.map((param) => `\t${goPascal(param.key)}: "…",`),
        `}${
          first.confirmation.required || first.idempotency.callerKeyRequired
            ? `, ${pkg}.CallOptions{${first.confirmation.required ? "Confirm: true" : ""}${
                first.confirmation.required && first.idempotency.callerKeyRequired ? ", " : ""
              }${first.idempotency.callerKeyRequired ? 'IdempotencyKey: "order-1234"' : ""}}`
            : ""
        })`,
        "```",
      ].join("\n")
    : "_This bundle has no approved operations yet._";
  return `# ${plan.service.displayName} — Go SDK

${plan.service.description}

Generated by Anvil from AIR. Zero dependencies — \`net/http\` and \`encoding/json\`
from the standard library, so \`sdk/go/\` can be vendored directly.

${usage}

The credential is read from \`${plan.auth.envVar}\` when \`New\` is called without
\`WithToken\`. It is never logged, echoed, or included in an error.

Safety is not advisory: an operation that requires confirmation returns
\`*Error\` with \`Code == "confirmation_required"\` before anything reaches the
network, and a transient failure on a mutation that cannot prove idempotence
returns \`"unsafe_retry_blocked"\` rather than being sent twice.

See \`../README.md\` for the full cross-language contract.
`;
}

function operationsFile(plan: SdkPlan): string {
  const rows = plan.operations.map((op) => {
    const params = op.params
      .map(
        (param) =>
          `\t\t\t{WireName: ${g(param.wireName)}, Key: ${g(param.key)}, In: ${g(param.in)}, Required: ${param.required}},`,
      )
      .join("\n");
    const body = op.body
      ? `&BodySpec{Required: ${op.body.required}, ContentType: ${g(op.body.contentType)}, Projection: ${g(op.body.projection)}, Fields: []BodyFieldSpec{${op.body.fields
          .map(
            (field) =>
              `{WireName: ${g(field.wireName)}, Key: ${g(field.key)}, Required: ${field.required}}`,
          )
          .join(", ")}}}`
      : "nil";
    const carrier = op.idempotency.carrier
      ? `&CarrierSpec{Mechanism: ${g(op.idempotency.carrier.mechanism)}, Key: ${g(op.idempotency.carrier.key)}, Path: ${
          op.idempotency.carrier.mechanism === "body"
            ? `[]string{${op.idempotency.carrier.path.map((segment) => g(segment)).join(", ")}}`
            : "nil"
        }}`
      : "nil";
    return `\t${g(op.names.pascal)}: {
		ID:         ${g(op.id)},
		HTTPMethod: ${g(op.httpMethod)},
		WireProtocol: ${g(op.wireProtocol)},${
      op.wireBinding
        ? `\n\t\tSoap: &SoapBinding{SoapAction: ${g(op.wireBinding.soapAction ?? "")}, EnvelopeNamespace: ${g(op.wireBinding.envelopeNamespace)}, BodyNamespace: ${g(op.wireBinding.bodyNamespace)}, BodyElement: ${g(op.wireBinding.bodyElement)}, ResponseElement: ${g(op.wireBinding.responseElement ?? "")}, ContentType: ${g(op.wireBinding.contentType)}, SoapVersion: ${g(op.wireBinding.soapVersion)}},`
        : ""
    }
		Path:       ${g(op.path)},
		Effect:     ${g(op.effect)},
		Params: []ParamSpec{
${params}
		},
		Body: ${body},
		Idempotency: IdempotencySpec{Mode: ${g(op.idempotency.mode)}, KeyDerivation: ${g(op.idempotency.keyDerivation)}, CallerKeyRequired: ${op.idempotency.callerKeyRequired}, Carrier: ${carrier}},
		Retry: RetrySpec{Mode: ${g(op.retry.mode)}, MaxAttempts: ${op.retry.maxAttempts}, Backoff: ${g(op.retry.backoff)}, BaseDelayMs: ${op.retry.baseDelayMs}, MaxDelayMs: ${op.retry.maxDelayMs}, RetryStatuses: []int{${op.retry.retryStatuses.join(", ")}}, RetryTransport: ${op.retry.retryTransport}},
		Confirmation: ConfirmationSpec{Required: ${op.confirmation.required}, HumanApproval: ${op.confirmation.humanApproval}, Reason: ${g(op.confirmation.reason ?? "")}},
	},`;
  });
  return `// Generated by Anvil. Do not edit — regenerate from AIR.
//
// One row per approved operation. An operation still in review is absent here,
// which is why it cannot be called: the SDK has no way to name it.

package ${goPackage(plan)}

// Operations is every approved operation, keyed by its Go method name.
var Operations = map[string]OperationSpec{
${rows.join("\n")}
}
`;
}

function clientFile(plan: SdkPlan): string {
  const pkg = goPackage(plan);
  const methods = plan.operations.map((op) => goMethod(op)).join("\n\n");
  const inputs = plan.operations.map((op) => goInputStruct(op)).join("\n\n");
  return `// Generated by Anvil. Do not edit — regenerate from AIR.

package ${pkg}

import (
	"context"
	"math/rand"
	"net/http"
	"os"
	"time"
)

// DefaultBaseURL is the base URL recorded in AIR at compile time.
const DefaultBaseURL = ${g(plan.service.baseUrl)}

// TokenEnvVar is the environment variable read when no token is supplied.
const TokenEnvVar = ${g(plan.auth.envVar)}

const userAgent = ${g(`anvil-sdk-${plan.service.id}/${plan.service.version} (go)`)}

// AuthCarrier is where the credential travels on the wire.
type AuthCarrier struct {
	In     string
	Name   string
	Scheme string
}

var authCarrier = ${
    plan.auth.carrier
      ? `&AuthCarrier{In: ${g(plan.auth.carrier.in)}, Name: ${g(plan.auth.carrier.name)}, Scheme: ${g(plan.auth.carrier.scheme ?? "")}}`
      : "(*AuthCarrier)(nil)"
  }

type clientConfig struct {
	baseURL string
	// protocolFacade is the operator's stated reason that baseURL really does
	// serve the synthesized coordinates of a non-HTTP/JSON source over
	// HTTP+JSON. A declaration, never an inference.
	protocolFacade string
	token          string
	authCarrier *AuthCarrier
	timeout     time.Duration
	httpClient  *http.Client
	random      func() float64
	sleep       func(time.Duration)
	userAgent   string
}

// Client is ${plan.service.description}
//
// Every method is one approved operation. The safety gates live in invoke, so
// no method can skip them.
type Client struct {
	config clientConfig
}

// Option configures a Client.
type Option func(*clientConfig)

// WithBaseURL overrides the compiled-in upstream base URL.
func WithBaseURL(baseURL string) Option {
	return func(config *clientConfig) { config.baseURL = baseURL }
}

// WithProtocolFacade declares that the base URL really does serve the
// synthesized coordinates of a non-HTTP/JSON source (SOAP, GraphQL, gRPC) over
// HTTP+JSON. Without it those operations are refused rather than sent.
func WithProtocolFacade(reason string) Option {
	return func(config *clientConfig) { config.protocolFacade = reason }
}

// WithToken sets the credential this SDK carries. It is never logged, echoed,
// or included in an error.
func WithToken(token string) Option {
	return func(config *clientConfig) { config.token = token }
}

// WithHTTPClient injects a transport, for tests and embedders.
func WithHTTPClient(httpClient *http.Client) Option {
	return func(config *clientConfig) { config.httpClient = httpClient }
}

// WithTimeout sets the per-request deadline.
func WithTimeout(timeout time.Duration) Option {
	return func(config *clientConfig) { config.timeout = timeout }
}

// WithRandom injects the jitter source, so a retry schedule is deterministic
// under test.
func WithRandom(random func() float64) Option {
	return func(config *clientConfig) { config.random = random }
}

// WithSleep injects the backoff sleep, so a retry schedule is assertable.
func WithSleep(sleep func(time.Duration)) Option {
	return func(config *clientConfig) { config.sleep = sleep }
}

// New builds a client. Without WithToken it reads ${plan.auth.envVar}.
func New(options ...Option) (*Client, error) {
	config := clientConfig{
		baseURL:        DefaultBaseURL,
		protocolFacade: os.Getenv("ANVIL_PROTOCOL_FACADE"),
		token:          os.Getenv(TokenEnvVar),
		authCarrier: authCarrier,
		timeout:     30 * time.Second,
		httpClient:  http.DefaultClient,
		random:      rand.Float64,
		userAgent:   userAgent,
	}
	for _, option := range options {
		option(&config)
	}
	if config.baseURL == "" {
		return nil, &Error{
			Code:              ${g("validation_error")},
			Operation:         ${g(plan.service.id)},
			Message:           "No base URL: the compiled model records no server, so one must be passed with WithBaseURL.",
			RequiredArguments: []string{"WithBaseURL"},
		}
	}
	if config.httpClient == nil {
		config.httpClient = http.DefaultClient
	}
	if config.random == nil {
		config.random = rand.Float64
	}
	return &Client{config: config}, nil
}

${inputs}

${methods}
`;
}

function goInputStruct(op: SdkOperation): string {
  const fields: string[] = [];
  const assignments: string[] = [];
  const push = (field: SdkField, source: string) => {
    const name = goPascal(field.key);
    const doc = field.description ? `\t// ${field.description}\n` : "";
    fields.push(`${doc}\t${name} ${goType(field)} \`json:${g(`${field.key},omitempty`)}\``);
    if (field.required) {
      assignments.push(`\tpayload[${g(field.key)}] = in.${name}`);
    } else if (isPointer(field)) {
      assignments.push(`\tif in.${name} != nil {\n\t\tpayload[${g(field.key)}] = *in.${name}\n\t}`);
    } else {
      assignments.push(`\tif in.${name} != nil {\n\t\tpayload[${g(field.key)}] = in.${name}\n\t}`);
    }
    void source;
  };
  for (const param of op.params) push(param, param.in);
  if (op.body?.projection === "fields") {
    for (const field of op.body.fields) push(field, "body");
  } else if (op.body) {
    push(
      {
        wireName: "body",
        key: "body",
        required: op.body.required,
        type: "any",
        description: `The request body, sent verbatim (content type ${op.body.contentType}).`,
      },
      "body",
    );
  }
  return `// ${op.names.pascal}Input is the input for ${op.canonicalName}.
type ${op.names.pascal}Input struct {
${fields.length > 0 ? fields.join("\n") : "\t// This operation takes no input."}
}

func (in ${op.names.pascal}Input) payload() map[string]any {
	payload := map[string]any{}
${assignments.join("\n")}
	return payload
}`;
}

function goMethod(op: SdkOperation): string {
  const doc = [`// ${op.names.pascal} — ${op.description}`, "//"]
    .concat(safetyNotes(op).flatMap((note) => wrap(note, 72).map((line) => `// ${line}`)))
    .join("\n");
  const lines = [
    doc,
    `func (c *Client) ${op.names.pascal}(ctx context.Context, in ${op.names.pascal}Input, options ...CallOptions) (any, error) {`,
    `\treturn invoke(ctx, c.config, Operations[${g(op.names.pascal)}], in.payload(), firstCallOptions(options))`,
    "}",
  ];

  const page = op.pagination;
  if (page?.cursorKey && page.nextField) {
    lines.push(
      "",
      `// ${op.names.pascal}Pager pages through ${op.canonicalName} until the upstream stops`,
      "// handing back a continuation.",
      `type ${op.names.pascal}Pager struct {
	client  *Client
	input   ${op.names.pascal}Input
	options CallOptions
	cursor  string
	done    bool
	seen    map[string]bool
}

// ${op.names.pascal}Paginated builds a pager over ${op.canonicalName}.
func (c *Client) ${op.names.pascal}Paginated(in ${op.names.pascal}Input, options ...CallOptions) *${op.names.pascal}Pager {
	return &${op.names.pascal}Pager{client: c, input: in, options: firstCallOptions(options), seen: map[string]bool{}}
}

// Next returns the next page. The second result is false once the upstream
// stops handing back a continuation.
func (p *${op.names.pascal}Pager) Next(ctx context.Context) (any, bool, error) {
	if p.done {
		return nil, false, nil
	}
	payload := p.input.payload()
	if p.cursor != "" {
		payload[${g(page.cursorKey)}] = p.cursor
	}
	result, err := invoke(ctx, p.client.config, Operations[${g(op.names.pascal)}], payload, p.options)
	if err != nil {
		return nil, false, err
	}
	next, ok := field(result, ${g(page.nextField)}).(string)
	// A server that echoes its own cursor would spin this loop forever; stop
	// instead of paging the same page until the process is killed.
	if !ok || next == "" || p.seen[next] {
		p.done = true
	} else {
		p.seen[next] = true
		p.cursor = next
	}
	return result, true, nil
}`,
    );
  }

  const contract = op.async;
  if (contract?.statusMethodBase && contract.statusJobIdKey && contract.terminalStates.length > 0) {
    const statusPascal = goPascal(contract.statusMethodBase);
    const statusJobIdKey = contract.statusJobIdKey;
    lines.push(
      "",
      `// WaitFor${op.names.pascal} — ${contract.instruction}`,
      "//",
      "// It polls at the interval the contract declares and returns the first status",
      "// response in a terminal state. Every field name below is the one AIR",
      "// resolved — none is guessed.",
      `func (c *Client) WaitFor${op.names.pascal}(ctx context.Context, submitResult any, timeout time.Duration) (any, error) {
	handle, ok := field(submitResult, ${g(contract.jobIdField)}).(string)
	if !ok || handle == "" {
		return nil, &Error{Code: "schema_mismatch", Operation: ${g(op.id)}, Message: "The submit response carried no ${contract.jobIdField} to poll on."}
	}
	if timeout <= 0 {
		timeout = ${contract.pollIntervalSeconds * 60} * time.Second
	}
	deadline := time.Now().Add(timeout)
	terminal := map[string]bool{${contract.terminalStates.map((state) => `${g(state)}: true`).join(", ")}}
	for {
		status, err := c.${statusPascal}(ctx, ${statusPascal}Input{${goPascal(statusJobIdKey)}: handle})
		if err != nil {
			return nil, err
		}
		if state, isString := field(status, ${g(contract.stateField ?? "state")}).(string); isString && terminal[state] {
			return status, nil
		}
		if time.Now().After(deadline) {
			return nil, &Error{Code: "upstream_timeout", Operation: ${g(op.id)}, Message: "${op.canonicalName} did not reach a terminal state before the wait deadline.", Retryable: true}
		}
		if err := sleepFor(ctx, ${contract.pollIntervalSeconds * 1000}, c.config.sleep); err != nil {
			return nil, err
		}
	}
}`,
    );
  }
  return lines.join("\n");
}
