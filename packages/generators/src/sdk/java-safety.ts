/**
 * The Java SDK's `Safety.java`: the retry gate, the Retry-After arithmetic,
 * and the idempotency key derivation, mirrored from the Anvil runtime.
 * Identical for every service, so the four SDKs and the runtime make one
 * decision.
 */

export function safetyFile(pkg: string): string {
  return `// Generated by Anvil. Do not edit — regenerate from AIR.
package ${pkg};

import java.nio.charset.StandardCharsets;
import java.security.MessageDigest;
import java.security.NoSuchAlgorithmException;
import java.time.Instant;
import java.time.ZonedDateTime;
import java.time.format.DateTimeFormatter;
import java.time.format.DateTimeParseException;
import java.util.ArrayList;
import java.util.Collections;
import java.util.List;
import java.util.Map;
import java.util.TreeMap;

/**
 * The safety hot path, mirrored from the Anvil runtime. Identical decisions in
 * every language Anvil emits: the same retry gate, the same Retry-After
 * arithmetic, the same idempotency key derivation.
 */
public final class Safety {

  /** The runtime-wide ceiling on a single pre-attempt sleep. */
  public static final long MAX_RETRY_DELAY_MS = 20000L;

  public static final int MAX_IDEMPOTENCY_KEY_BYTES = 255;

  private Safety() {}

  /**
   * Whether automatic retry is safe for this operation. The guard behind the
   * whole trust wedge: a mutation that is not provably idempotent is never
   * retried, no matter what the policy says.
   */
  public static boolean retryIsSafe(OperationSpec spec, boolean hasIdempotencyKey) {
    if (!"safe".equals(spec.retry.mode)) {
      return false;
    }
    if ("read".equals(spec.effect)) {
      return true;
    }
    String mode = spec.idempotency.mode;
    if ("natural".equals(mode) || "client_id".equals(mode)) {
      return true;
    }
    if ("required".equals(mode) || "key_supported".equals(mode)) {
      return hasIdempotencyKey;
    }
    return false;
  }

  /** Bounded exponential backoff with full jitter. {@code attempt} is 1-based. */
  public static long computeBackoffMs(int attempt, OperationSpec.Retry retry, double draw) {
    if ("none".equals(retry.backoff)) {
      return 0L;
    }
    if ("fixed".equals(retry.backoff)) {
      return Math.min(retry.baseDelayMs, retry.maxDelayMs);
    }
    double exp = Math.min((double) retry.maxDelayMs, retry.baseDelayMs * Math.pow(2, attempt - 1));
    if ("exponential".equals(retry.backoff)) {
      return (long) exp;
    }
    return (long) (draw * exp);
  }

  /**
   * The upstream's own answer to "when should I come back?" (RFC 9110 section
   * 10.2.3), in milliseconds from {@code now}. Both wire forms are accepted:
   * delta-seconds and an HTTP-date. Returns -1 when the value is not a valid
   * Retry-After at all, or names an instant already past — in both cases we
   * have learned nothing.
   */
  public static long parseRetryAfter(String value, Instant now) {
    if (value == null) {
      return -1L;
    }
    String raw = value.trim();
    if (raw.isEmpty()) {
      return -1L;
    }
    boolean digits = true;
    for (int index = 0; index < raw.length(); index++) {
      if (!Character.isDigit(raw.charAt(index))) {
        digits = false;
        break;
      }
    }
    if (digits) {
      try {
        // Saturate rather than discard: an absurd delta is still an instruction
        // to stay away, and dropping it would let us hammer a service that just
        // asked us to stop.
        return Math.multiplyExact(Long.parseLong(raw), 1000L);
      } catch (ArithmeticException overflow) {
        return Long.MAX_VALUE;
      } catch (NumberFormatException malformed) {
        return -1L;
      }
    }
    try {
      ZonedDateTime at = ZonedDateTime.parse(raw, DateTimeFormatter.RFC_1123_DATE_TIME);
      long delta = at.toInstant().toEpochMilli() - now.toEpochMilli();
      return delta < 0 ? -1L : delta;
    } catch (DateTimeParseException malformed) {
      return -1L;
    }
  }

  /** What to do before the next attempt. */
  public static final class RetryDecision {
    /** True when the attempt budget ends instead of sleeping. */
    public final boolean stop;

    public final long delayMs;

    RetryDecision(boolean stop, long delayMs) {
      this.stop = stop;
      this.delayMs = delayMs;
    }
  }

  /**
   * Resolve the pre-attempt delay, honoring upstream backpressure over our own
   * guess.
   *
   * <p>An upstream asking for LONGER than the ceiling ends the attempt budget
   * rather than clamping the sleep — clamping would mean knocking again early,
   * which is how a rate limit becomes a ban. An upstream asking for LESS keeps
   * our backoff: Retry-After is a floor on staying away, not permission to come
   * back sooner and collapse jitter into a tight loop.
   */
  public static RetryDecision resolveRetryDelay(
      int attempt, OperationSpec.Retry retry, long retryAfterMs, double draw) {
    if (retryAfterMs >= 0 && retryAfterMs > MAX_RETRY_DELAY_MS) {
      return new RetryDecision(true, retryAfterMs);
    }
    long backoffMs = computeBackoffMs(attempt, retry, draw);
    if (retryAfterMs < 0 || retryAfterMs <= backoffMs) {
      return new RetryDecision(false, backoffMs);
    }
    return new RetryDecision(false, retryAfterMs);
  }

  /** Deterministic canonical JSON: object keys sorted, so equal inputs hash equal. */
  public static String canonicalJson(Object value) {
    return Json.write(sortKeys(value));
  }

  @SuppressWarnings("unchecked")
  private static Object sortKeys(Object value) {
    if (value instanceof Map) {
      Map<String, Object> sorted = new TreeMap<String, Object>();
      for (Map.Entry<?, ?> entry : ((Map<?, ?>) value).entrySet()) {
        sorted.put(String.valueOf(entry.getKey()), sortKeys(entry.getValue()));
      }
      return sorted;
    }
    if (value instanceof Iterable) {
      List<Object> out = new ArrayList<Object>();
      for (Object item : (Iterable<Object>) value) {
        out.add(sortKeys(item));
      }
      return Collections.unmodifiableList(out);
    }
    return value;
  }

  /** Portable caller-key contract: visible ASCII, at most 255 bytes. */
  public static boolean idempotencyKeyIsTransportSafe(String value) {
    if (value == null || value.isEmpty()) {
      return false;
    }
    if (value.getBytes(StandardCharsets.UTF_8).length > MAX_IDEMPOTENCY_KEY_BYTES) {
      return false;
    }
    for (int index = 0; index < value.length(); index++) {
      char character = value.charAt(index);
      if (character < 0x21 || character > 0x7e) {
        return false;
      }
    }
    return true;
  }

  /** A stable fingerprint: sha256 over the operation id and canonical input. */
  public static String requestFingerprint(String operationId, Map<String, Object> payload) {
    try {
      MessageDigest digest = MessageDigest.getInstance("SHA-256");
      digest.update(operationId.getBytes(StandardCharsets.UTF_8));
      digest.update(new byte[] {0});
      digest.update(canonicalJson(payload).getBytes(StandardCharsets.UTF_8));
      byte[] bytes = digest.digest();
      StringBuilder out = new StringBuilder(bytes.length * 2);
      for (byte item : bytes) {
        out.append(Character.forDigit((item >> 4) & 0xf, 16));
        out.append(Character.forDigit(item & 0xf, 16));
      }
      return out.toString();
    } catch (NoSuchAlgorithmException impossible) {
      throw new IllegalStateException("SHA-256 is required by the Java platform", impossible);
    }
  }

  /**
   * Caller-supplied key, else fingerprint derivation, else none. Returns null
   * when no key can be produced; the caller decides whether that is a refusal.
   */
  public static String resolveIdempotencyKey(
      OperationSpec spec, String provided, Map<String, Object> payload) {
    if (provided != null && !provided.isEmpty()) {
      if (!idempotencyKeyIsTransportSafe(provided)) {
        throw AnvilException.builder("validation_error", spec.id,
                "An idempotency key must be 1 to 255 bytes of visible ASCII with no spaces or control characters.")
            .build();
      }
      return provided;
    }
    if ("request_fingerprint".equals(spec.idempotency.keyDerivation)) {
      return "anvil-" + requestFingerprint(spec.id, payload).substring(0, 32);
    }
    return null;
  }
}
`;
}
