function traceId(): string {
  return typeof crypto.randomUUID === "function"
    ? crypto.randomUUID()
    : Math.random().toString(16).slice(2) + Date.now().toString(16);
}

/**
 * The transport gate. The confirmation gate asks whether the caller intends the
 * effect; this asks whether this client can express the call at all. A SOAP,
 * GraphQL, or gRPC operation arrives with a path Anvil invented, and sending
 * JSON to it would be a well-formed lie — indistinguishable on the wire from a
 * real request. Mirrors the runtime's own gate so every surface refuses alike.
 */
function assertWireExecutable(spec: OperationSpec, context: InvokeContext): void {
  // A subscription is a bounded event-stream window with an array answer.
  // This client is request/response, and a protocol facade declares
  // coordinates, not framing — so the refusal holds with a facade declared.
  // The runtime and MCP surfaces read this wire; use one of those.
  if (spec.wireProtocol === "graphql_sse") {
    throw new AnvilError({
      code: "unsupported_operation",
      operation: spec.id,
      traceId: traceId(),
      message:
        spec.id +
        " is a GraphQL subscription, observed through a bounded Server-Sent Events " +
        "window. This client is request/response and cannot hold that window open, " +
        "and a protocol facade cannot change the framing of an event stream. " +
        "Call it through the generated MCP server or CLI, which share the runtime " +
        "that reads this wire.",
    });
  }
  if (spec.wireProtocol === "http_json" || context.protocolFacade !== undefined) return;
  // A protocol is speakable exactly when the compiler recovered a binding.
  if (spec.wireProtocol === "soap" && spec.soap) return;
  if (spec.wireProtocol === "graphql" && spec.graphql) return;
  throw new AnvilError({
    code: "unsupported_operation",
    operation: spec.id,
    traceId: traceId(),
    message:
      spec.id +
      " speaks " +
      spec.wireProtocol +
      ", which this client cannot put on the wire: " +
      spec.httpMethod +
      " " +
      spec.path +
      " is a coordinate Anvil synthesized, not an address the service serves. " +
      "Point baseUrl at a facade that really does serve it over HTTP+JSON and " +
      "pass protocolFacade with the reason, so the assumption is recorded.",
  });
}

/** The confirmation gate. Refuses before anything reaches the wire. */
function assertConfirmed(spec: OperationSpec, options: CallOptions): void {
  if (!spec.confirmation.required || options.confirm === true) return;
  const audience = spec.confirmation.humanApproval
    ? "This effect needs explicit human approval, not a self-confirmation."
    : "Pass { confirm: true } once you intend the effect.";
  throw new AnvilError({
    code: "confirmation_required",
    operation: spec.id,
    traceId: traceId(),
    message:
      spec.id +
      " requires confirmation" +
      (spec.confirmation.reason ? ": " + spec.confirmation.reason : "") +
      ". " +
      audience,
    requiredFlags: ["confirm"],
  });
}

