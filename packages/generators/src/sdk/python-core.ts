/**
 * The Python SDK's decision core — the modules that are byte-identical for
 * every service Anvil compiles.
 *
 * They live apart from the per-service projection on purpose: the code that
 * decides whether a call is allowed to happen is one reviewed implementation,
 * and generation only ever adds rows to the table it reads.
 */

const p = (value: unknown): string => JSON.stringify(value);

export function errorsModule(plan: SdkPlan): string {
  return `"""Generated by Anvil. Do not edit — regenerate from AIR.

The Anvil error taxonomy (spec section 10). Anvil never leaks raw upstream
chaos as the primary interface: every failure arrives as 'AnvilError' with a
code from this list and the next action attached.
"""

from typing import Any, Dict, List, Optional

ERROR_CODES = (
${plan.errorCodes.map((code) => `    ${p(code)},`).join("\n")}
)


class AnvilError(Exception):
    """A structured refusal. 'code' is always one of 'ERROR_CODES'."""

    def __init__(
        self,
        code: str,
        message: str,
        operation: str,
        trace_id: str = "",
        retryable: bool = False,
        safe_to_retry: bool = False,
        upstream: Optional[Dict[str, Any]] = None,
        required_arguments: Optional[List[str]] = None,
        details: Any = None,
        retry_after_ms: Optional[int] = None,
    ) -> None:
        super().__init__(message)
        self.code = code
        self.message = message
        self.operation = operation
        self.trace_id = trace_id
        self.retryable = retryable
        self.safe_to_retry = safe_to_retry
        self.upstream = upstream
        #: What the caller must supply, for confirmation_required / idempotency_required.
        self.required_arguments = required_arguments or []
        self.details = details
        #: The upstream's own backpressure instruction, when it gave one.
        self.retry_after_ms = retry_after_ms

    def __repr__(self) -> str:  # pragma: no cover - debugging aid
        return "AnvilError(code=%r, operation=%r, message=%r)" % (
            self.code,
            self.operation,
            self.message,
        )


def http_status_to_error_code(status: int) -> str:
    """Map an upstream HTTP status onto the Anvil error taxonomy."""
    if status in (400, 422):
        return "validation_error"
    if status == 401:
        return "auth_required"
    if status == 403:
        return "permission_denied"
    if status in (404, 410):
        return "not_found"
    if status == 408:
        return "upstream_timeout"
    if status == 409:
        return "conflict"
    if status == 429:
        return "rate_limited"
    if status in (502, 503):
        return "upstream_unavailable"
    if status == 504:
        return "upstream_timeout"
    if status >= 500:
        return "unknown_upstream_error"
    if status >= 400:
        return "validation_error"
    return "unknown_upstream_error"


def is_retryable_code(code: str) -> bool:
    """Whether a code is inherently retryable, before the idempotency gate."""
    return code in ("rate_limited", "upstream_timeout", "upstream_unavailable")
`;
}

export function safetyModule(): string {
  return `"""Generated by Anvil. Do not edit — regenerate from AIR.

The safety hot path, mirrored from '@anvil/runtime'. Identical decisions in
every language Anvil emits: the same retry gate, the same Retry-After
arithmetic, the same idempotency key derivation.
"""

import calendar
import hashlib
import json
import random as _random
import re
from typing import Any, Optional, Tuple

#: The runtime-wide ceiling on a single pre-attempt sleep.
MAX_RETRY_DELAY_MS = 20000
MAX_IDEMPOTENCY_KEY_BYTES = 255

_MONTHS = (
    "jan", "feb", "mar", "apr", "may", "jun",
    "jul", "aug", "sep", "oct", "nov", "dec",
)
_IMF_FIXDATE = re.compile(
    r"^[A-Za-z]{3}, ([0-9]{2}) ([A-Za-z]{3}) ([0-9]{4}) "
    r"([0-9]{2}):([0-9]{2}):([0-9]{2}) GMT$"
)
_VISIBLE_ASCII = re.compile(r"^[\\x21-\\x7e]+$")


def retry_is_safe(spec: Any, has_idempotency_key: bool) -> bool:
    """Whether automatic retry is safe for this operation.

    The guard behind the whole trust wedge: a mutation that is not provably
    idempotent is never retried, no matter what the policy says.
    """
    if spec.retry["mode"] != "safe":
        return False
    if spec.effect == "read":
        return True
    mode = spec.idempotency["mode"]
    if mode in ("natural", "client_id"):
        return True
    if mode in ("required", "key_supported"):
        return has_idempotency_key
    return False


def compute_backoff_ms(attempt: int, retry: Any, rng: Any = None) -> int:
    """Bounded exponential backoff with full jitter. 'attempt' is 1-based."""
    backoff = retry["backoff"]
    base = retry["baseDelayMs"]
    ceiling = retry["maxDelayMs"]
    if backoff == "none":
        return 0
    if backoff == "fixed":
        return min(base, ceiling)
    exp = min(ceiling, base * (2 ** (attempt - 1)))
    if backoff == "exponential":
        return int(exp)
    draw = (rng or _random.random)()
    return int(draw * exp)


def parse_retry_after(value: str, now_ms: int) -> Optional[int]:
    """The upstream's own answer to "when should I come back?" in milliseconds.

    Both wire forms are accepted: delta-seconds and an HTTP-date. Returns None
    when the value is not a valid Retry-After at all, or names an instant
    already past — in both cases we have learned nothing.
    """
    raw = value.strip()
    if not raw:
        return None
    if raw.isdigit():
        # Saturate rather than discard: an absurd delta is still an instruction
        # to stay away, and dropping it would let us hammer a service that just
        # asked us to stop.
        return int(raw) * 1000
    match = _IMF_FIXDATE.match(raw)
    if not match:
        return None
    day = int(match.group(1))
    try:
        month = _MONTHS.index(match.group(2).lower()) + 1
    except ValueError:
        return None
    year = int(match.group(3))
    hour, minute, second = int(match.group(4)), int(match.group(5)), int(match.group(6))
    if day < 1 or day > 31 or hour > 23 or minute > 59 or second > 59:
        return None
    try:
        at_ms = calendar.timegm((year, month, day, hour, minute, second, 0, 0, 0)) * 1000
    except (ValueError, OverflowError):
        return None
    delta = at_ms - now_ms
    return None if delta < 0 else int(delta)


def resolve_retry_delay(
    attempt: int, retry: Any, retry_after_ms: Optional[int], rng: Any = None
) -> Tuple[str, int]:
    """Resolve the pre-attempt delay, honoring upstream backpressure.

    Returns '("wait", delay_ms)' or '("stop", retry_after_ms)'.

    An upstream asking for LONGER than the ceiling ends the attempt budget
    rather than clamping the sleep — clamping would mean knocking again early,
    which is how a rate limit becomes a ban. An upstream asking for LESS keeps
    our backoff: Retry-After is a floor on staying away, not permission to come
    back sooner and collapse jitter into a tight loop.
    """
    if retry_after_ms is not None and retry_after_ms > MAX_RETRY_DELAY_MS:
        return ("stop", retry_after_ms)
    backoff_ms = compute_backoff_ms(attempt, retry, rng)
    if retry_after_ms is None or retry_after_ms <= backoff_ms:
        return ("wait", backoff_ms)
    return ("wait", retry_after_ms)


def canonical_json(value: Any) -> str:
    """Deterministic canonical JSON: keys sorted, so equal inputs hash equal."""
    return json.dumps(value, sort_keys=True, separators=(",", ":"))


def idempotency_key_is_transport_safe(value: str) -> bool:
    """Portable caller-key contract: visible ASCII, at most 255 bytes."""
    return bool(value) and len(value.encode("utf-8")) <= MAX_IDEMPOTENCY_KEY_BYTES and bool(
        _VISIBLE_ASCII.match(value)
    )


def request_fingerprint(operation_id: str, payload: Any) -> str:
    """A stable fingerprint: sha256 over the operation id and canonical input."""
    digest = hashlib.sha256()
    digest.update(operation_id.encode("utf-8"))
    digest.update(b"\\x00")
    digest.update(canonical_json(payload).encode("utf-8"))
    return digest.hexdigest()


def resolve_idempotency_key(spec: Any, provided: Optional[str], payload: Any) -> Optional[str]:
    """Caller-supplied key, else fingerprint derivation, else none.

    Returns None when no key can be produced; the caller decides whether that
    is a refusal.
    """
    if provided:
        if not idempotency_key_is_transport_safe(provided):
            raise ValueError(
                "An idempotency key must be 1 to 255 bytes of visible ASCII "
                "with no spaces or control characters."
            )
        return provided
    if spec.idempotency["keyDerivation"] == "request_fingerprint":
        return "anvil-" + request_fingerprint(spec.id, payload)[:32]
    return None
`;
}

