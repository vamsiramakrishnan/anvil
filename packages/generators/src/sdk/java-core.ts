/**
 * `Mtls.java` — an `SSLContext` built from PEM client-certificate material,
 * emitted only for a service whose auth scheme is `mtls`.
 *
 * `HttpClient.Builder.sslContext` already lets a caller supply any TLS
 * configuration, so mTLS needs nothing new in the call path — only something
 * that builds the right `SSLContext`, using only `java.security` /
 * `javax.net.ssl`. The private key MUST be PKCS#8
 * (`-----BEGIN PRIVATE KEY-----`); a traditional PKCS#1 RSA key
 * (`-----BEGIN RSA PRIVATE KEY-----`) is not directly loadable by
 * `KeyFactory` and must be converted first, e.g.
 * `openssl pkcs8 -topk8 -nocrypt -in key.pem -out key-pkcs8.pem`.
 */
export function mtlsFile(pkg: string): string {
  return `// Generated by Anvil. Do not edit — regenerate from AIR.
package ${pkg};

import java.io.ByteArrayInputStream;
import java.io.IOException;
import java.io.UncheckedIOException;
import java.nio.charset.StandardCharsets;
import java.nio.file.Files;
import java.nio.file.Path;
import java.security.GeneralSecurityException;
import java.security.KeyFactory;
import java.security.KeyStore;
import java.security.PrivateKey;
import java.security.cert.Certificate;
import java.security.cert.CertificateFactory;
import java.security.spec.PKCS8EncodedKeySpec;
import java.util.Base64;
import javax.net.ssl.KeyManagerFactory;
import javax.net.ssl.SSLContext;
import javax.net.ssl.TrustManagerFactory;

/**
 * Mutual-TLS transport. The credential material is never logged, echoed, or
 * included in an exception.
 */
public final class Mtls {

  private Mtls() {}

  /** A value that already names a readable file is read as-is; anything else is used as literal PEM text. */
  private static String resolveText(String value) {
    if (value.trim().startsWith("-----BEGIN")) {
      return value;
    }
    try {
      return new String(Files.readAllBytes(Path.of(value)), StandardCharsets.UTF_8);
    } catch (IOException e) {
      throw new UncheckedIOException(e);
    }
  }

  private static byte[] pemToDer(String pem) {
    StringBuilder base64 = new StringBuilder();
    for (String line : pem.split("\\\\r?\\\\n")) {
      if (!line.startsWith("-----")) {
        base64.append(line.trim());
      }
    }
    return Base64.getDecoder().decode(base64.toString());
  }

  private static PrivateKey parsePrivateKey(byte[] der) throws GeneralSecurityException {
    PKCS8EncodedKeySpec spec = new PKCS8EncodedKeySpec(der);
    try {
      return KeyFactory.getInstance("RSA").generatePrivate(spec);
    } catch (GeneralSecurityException rsaFailure) {
      return KeyFactory.getInstance("EC").generatePrivate(spec);
    }
  }

  /**
   * Build an SSLContext presenting the given PKCS#8 client certificate/key.
   * When {@code ca} is non-null, it — and only it — is trusted, mirroring how
   * the TypeScript, Python, and Go SDKs treat an explicit CA; otherwise the
   * platform's default trust store is used.
   */
  public static SSLContext buildContext(String certPem, String keyPem, String caPem) {
    try {
      CertificateFactory certFactory = CertificateFactory.getInstance("X.509");
      Certificate cert =
          certFactory.generateCertificate(new ByteArrayInputStream(pemToDer(resolveText(certPem))));
      PrivateKey key = parsePrivateKey(pemToDer(resolveText(keyPem)));

      KeyStore keyStore = KeyStore.getInstance("PKCS12");
      keyStore.load(null, null);
      keyStore.setKeyEntry("client", key, new char[0], new Certificate[] {cert});
      KeyManagerFactory keyManagerFactory =
          KeyManagerFactory.getInstance(KeyManagerFactory.getDefaultAlgorithm());
      keyManagerFactory.init(keyStore, new char[0]);

      TrustManagerFactory trustManagerFactory =
          TrustManagerFactory.getInstance(TrustManagerFactory.getDefaultAlgorithm());
      if (caPem != null && !caPem.isEmpty()) {
        Certificate ca =
            certFactory.generateCertificate(new ByteArrayInputStream(pemToDer(resolveText(caPem))));
        KeyStore trustStore = KeyStore.getInstance("PKCS12");
        trustStore.load(null, null);
        trustStore.setCertificateEntry("ca", ca);
        trustManagerFactory.init(trustStore);
      } else {
        trustManagerFactory.init((KeyStore) null);
      }

      SSLContext context = SSLContext.getInstance("TLS");
      context.init(
          keyManagerFactory.getKeyManagers(), trustManagerFactory.getTrustManagers(), null);
      return context;
    } catch (GeneralSecurityException | IOException e) {
      throw new IllegalStateException(
          "mTLS client certificate could not be loaded: " + e.getMessage(), e);
    }
  }
}
`;
}

/**
 * `Oauth.java` — an optional refresh helper for `oauth2_authorization_code`,
 * emitted only when the contract names a token endpoint. Never performs the
 * interactive authorization step; only exchanges an already-obtained refresh
 * token for a fresh access token (RFC 6749 section 6).
 */
export function oauthFile(pkg: string): string {
  return `// Generated by Anvil. Do not edit — regenerate from AIR.
package ${pkg};

import java.net.URI;
import java.net.http.HttpClient;
import java.net.http.HttpRequest;
import java.net.http.HttpResponse;
import java.nio.charset.StandardCharsets;
import java.time.Duration;
import java.time.Instant;
import java.util.Base64;
import java.util.Map;
import java.util.function.Supplier;

/**
 * Optional refresh helper for the authorization-code grant (RFC 6749 section
 * 6). Never performs the interactive authorization step, and never logs the
 * refresh token, client secret, or minted access token.
 */
public final class Oauth {

  private Oauth() {}

  /**
   * Build a token supplier that exchanges {@code refreshToken} at {@code
   * tokenEndpoint} and caches the access token in memory until shortly before
   * it expires.
   */
  public static Supplier<String> refreshingTokenProvider(
      String tokenEndpoint, String refreshToken, String clientId, String clientSecret) {
    HttpClient client = HttpClient.newHttpClient();
    Object[] cache = new Object[] {null, Instant.MIN};

    return () -> {
      synchronized (cache) {
        if (cache[0] != null && Instant.now().isBefore((Instant) cache[1])) {
          return (String) cache[0];
        }
        String form =
            "grant_type=refresh_token&refresh_token="
                + java.net.URLEncoder.encode(refreshToken, StandardCharsets.UTF_8)
                + "&client_id="
                + java.net.URLEncoder.encode(clientId, StandardCharsets.UTF_8);
        HttpRequest.Builder builder =
            HttpRequest.newBuilder(URI.create(tokenEndpoint))
                .timeout(Duration.ofSeconds(30))
                .header("content-type", "application/x-www-form-urlencoded")
                .POST(HttpRequest.BodyPublishers.ofString(form));
        if (clientSecret != null && !clientSecret.isEmpty()) {
          String basic =
              Base64.getEncoder()
                  .encodeToString((clientId + ":" + clientSecret).getBytes(StandardCharsets.UTF_8));
          builder.header("authorization", "Basic " + basic);
        }
        HttpResponse<String> response;
        try {
          response = client.send(builder.build(), HttpResponse.BodyHandlers.ofString());
        } catch (Exception e) {
          throw new IllegalStateException(
              "token refresh could not reach " + tokenEndpoint, e);
        }
        if (response.statusCode() < 200 || response.statusCode() >= 300) {
          // Never surface the response body: a token endpoint's error payload
          // can echo back the refresh token or client secret it was sent.
          throw new IllegalStateException(
              "token refresh failed with HTTP " + response.statusCode() + " from " + tokenEndpoint);
        }
        Object parsed = Json.parse(response.body());
        Map<?, ?> payload = parsed instanceof Map ? (Map<?, ?>) parsed : java.util.Collections.emptyMap();
        Object accessTokenValue = payload.get("access_token");
        String accessToken = accessTokenValue instanceof String ? (String) accessTokenValue : null;
        if (accessToken == null || accessToken.isEmpty()) {
          throw new IllegalStateException("token endpoint response carried no access_token");
        }
        Object expiresInValue = payload.get("expires_in");
        long expiresIn = expiresInValue instanceof Number ? ((Number) expiresInValue).longValue() : 300L;
        cache[0] = accessToken;
        cache[1] = Instant.now().plusSeconds(expiresIn - 30L);
        return accessToken;
      }
    };
  }
}
`;
}
