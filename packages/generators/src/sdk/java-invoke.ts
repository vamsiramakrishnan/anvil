/**
 * The Java SDK's call path: the single `Invoker.invoke` every generated method
 * funnels through (the retry gate and Retry-After arithmetic it reads live in
 * `java-safety.ts`). Identical for every service, so a method that skipped a
 * gate would have to be a change here rather than a quiet difference in one
 * emitted client.
 */

export function invokerFile(pkg: string): string {
  return `// Generated by Anvil. Do not edit — regenerate from AIR.
package ${pkg};

import java.io.IOException;
import java.net.URI;
import java.net.URLEncoder;
import java.net.http.HttpClient;
import java.net.http.HttpRequest;
import java.net.http.HttpResponse;
import java.nio.charset.StandardCharsets;
import java.time.Duration;
import java.time.Instant;
import java.util.ArrayList;
import java.util.Arrays;
import java.util.HashSet;
import java.util.Iterator;
import java.util.LinkedHashMap;
import java.util.List;
import java.util.Map;
import java.util.Optional;
import java.util.Set;
import java.util.UUID;

/**
 * The one call path. Every generated method funnels through {@link #invoke}, so
 * the gates below cannot be bypassed by a method that forgot to check.
 */
final class Invoker {

  /** Headers the transport owns; a caller override would break the contract. */
  private static final Set<String> RESERVED_HEADERS =
      new HashSet<String>(
          Arrays.asList(
              "authorization", "content-length", "content-type", "host", "transfer-encoding"));

  private Invoker() {}

  @SuppressWarnings("unchecked")
  static java.util.Map<String, Object> castMap(Object value) {
    return (java.util.Map<String, Object>) value;
  }

  /** The compiled query document for a GraphQL operation. Posted as handed, so
   *  no caller value is ever interpolated into a query. */
  public static final class GraphqlBinding {
    public final String document;
    public final String operationName;
    public final String rootField;

    public GraphqlBinding(String document, String operationName, String rootField) {
      this.document = document;
      this.operationName = operationName;
      this.rootField = rootField;
    }
  }

  /** The resolved client configuration one call runs under. */
  static final class Config {
    final String baseUrl;
    /**
     * The operator's stated reason that baseUrl really does serve the
     * synthesized coordinates of a non-HTTP/JSON source over HTTP+JSON. A
     * declaration, never an inference.
     */
    final String protocolFacade;

    final String token;
    /**
     * Delegated-token source for oauth2_authorization_code: called once per
     * request when set, taking priority over a static token. Never logged or
     * echoed — only its resolved return value reaches the wire, and only as a
     * header/query value, never in an exception.
     */
    final java.util.function.Supplier<String> tokenSupplier;
    final String authIn;
    final String authName;
    final String authScheme;
    final Duration timeout;
    final HttpClient httpClient;
    final String userAgent;
    final java.util.function.DoubleSupplier random;

    Config(
        String baseUrl,
        String protocolFacade,
        String token,
        java.util.function.Supplier<String> tokenSupplier,
        String authIn,
        String authName,
        String authScheme,
        Duration timeout,
        HttpClient httpClient,
        String userAgent,
        java.util.function.DoubleSupplier random) {
      this.baseUrl = baseUrl;
      this.protocolFacade = protocolFacade;
      this.token = token;
      this.tokenSupplier = tokenSupplier;
      this.authIn = authIn;
      this.authName = authName;
      this.authScheme = authScheme;
      this.timeout = timeout;
      this.httpClient = httpClient;
      this.userAgent = userAgent;
      this.random = random;
    }
  }

  /** A request ready to send, with the body it carries kept readable for a dry-run plan. */
  static final class Built {
    final HttpRequest request;
    final String body;

    Built(HttpRequest request, String body) {
      this.request = request;
      this.body = body;
    }
  }

  private static String traceId() {
    return UUID.randomUUID().toString();
  }

  /**
   * The transport gate. The confirmation gate asks whether the caller intends
   * the effect; this asks whether this client can express the call at all. A
   * SOAP, GraphQL, or gRPC operation arrives with a path Anvil invented, and
   * sending JSON to it would be a well-formed lie. Mirrors the runtime's own
   * gate so every surface refuses alike.
   */
  static void assertWireExecutable(OperationSpec spec, Config config) {
    // A subscription is a bounded event-stream window with an array answer.
    // This client is request/response, and a protocol facade declares
    // coordinates, not framing — so the refusal holds with a facade declared.
    if ("graphql_sse".equals(spec.wireProtocol)) {
      throw AnvilException.builder(
              "unsupported_operation",
              spec.id,
              spec.id
                  + " is a GraphQL subscription, observed through a bounded Server-Sent Events"
                  + " window. This client is request/response and cannot hold that window open,"
                  + " and a protocol facade cannot change the framing of an event stream. Call it"
                  + " through the generated MCP server or CLI, which share the runtime that reads"
                  + " this wire.")
          .traceId(traceId())
          .build();
    }
    if ("http_json".equals(spec.wireProtocol) || config.protocolFacade != null) {
      return;
    }
    // SOAP is speakable exactly when the compiler recovered a binding for it.
    if ("soap".equals(spec.wireProtocol) && spec.soap != null) {
      return;
    }
    if ("graphql".equals(spec.wireProtocol) && spec.graphql != null) {
      return;
    }
    throw AnvilException.builder(
            "unsupported_operation",
            spec.id,
            spec.id
                + " speaks "
                + spec.wireProtocol
                + ", which this client cannot put on the wire: "
                + spec.httpMethod
                + " "
                + spec.path
                + " is a coordinate Anvil synthesized, not an address the service serves."
                + " Point builder().baseUrl(...) at a facade that really does serve it over"
                + " HTTP+JSON and pass protocolFacade(...) with the reason, so the assumption"
                + " is recorded.")
        .traceId(traceId())
        .build();
  }

  /** The confirmation gate. Refuses before anything reaches the wire. */
  static void assertConfirmed(OperationSpec spec, CallOptions options) {
    if (!spec.confirmation.required || options.confirmed()) {
      return;
    }
    String audience =
        spec.confirmation.humanApproval
            ? "This effect needs explicit human approval, not a self-confirmation."
            : "Call CallOptions.none().confirm(true) once you intend the effect.";
    String reason =
        spec.confirmation.reason == null || spec.confirmation.reason.isEmpty()
            ? ""
            : ": " + spec.confirmation.reason;
    throw AnvilException.builder(
            "confirmation_required",
            spec.id,
            spec.id + " requires confirmation" + reason + ". " + audience)
        .traceId(traceId())
        .requiredArguments("confirm")
        .build();
  }

  /** The idempotency gate. A contract that demands a key gets one or a refusal. */
  static void assertKeyed(OperationSpec spec, String key) {
    if (!spec.idempotency.callerKeyRequired || (key != null && !key.isEmpty())) {
      return;
    }
    throw AnvilException.builder(
            "idempotency_required",
            spec.id,
            spec.id
                + " requires an idempotency key that Anvil cannot derive for you. Set"
                + " CallOptions.idempotencyKey — reuse the same value to retry the same intent.")
        .traceId(traceId())
        .requiredArguments("idempotencyKey")
        .build();
  }

  @SuppressWarnings("unchecked")
  private static Object setBodyCarrier(Object body, List<String> path, String value) {
    Map<String, Object> root =
        body instanceof Map
            ? new LinkedHashMap<String, Object>((Map<String, Object>) body)
            : new LinkedHashMap<String, Object>();
    Map<String, Object> cursor = root;
    for (int index = 0; index < path.size() - 1; index++) {
      Object existing = cursor.get(path.get(index));
      Map<String, Object> child =
          existing instanceof Map
              ? new LinkedHashMap<String, Object>((Map<String, Object>) existing)
              : new LinkedHashMap<String, Object>();
      cursor.put(path.get(index), child);
      cursor = child;
    }
    cursor.put(path.get(path.size() - 1), value);
    return root;
  }

  private static String scalar(Object value) {
    if (value instanceof String) {
      return (String) value;
    }
    if (value instanceof Double || value instanceof Float) {
      double asDouble = ((Number) value).doubleValue();
      if (asDouble == Math.rint(asDouble) && !Double.isInfinite(asDouble)) {
        return Long.toString((long) asDouble);
      }
    }
    return String.valueOf(value);
  }

  /**
   * Percent-encode one path segment. {@link URLEncoder} implements
   * form encoding, where a space becomes {@code +} — which in a path means a
   * literal plus, not a space — so the one difference is undone here.
   */
  private static String encodePath(String value) {
    return URLEncoder.encode(value, StandardCharsets.UTF_8).replace("+", "%20");
  }

  /**
   * Encode one query name or value. Form encoding is exactly right here, and
   * the {@code +} for a space is deliberately kept: the TypeScript, Python, and
   * Go SDKs all emit {@code +} in a query string, and four clients built from
   * one contract should put the same bytes on the wire.
   */
  private static String encodeQuery(String value) {
    return URLEncoder.encode(value, StandardCharsets.UTF_8);
  }

  /** Build the upstream request from the operation spec and caller payload. */
  static Built buildRequest(
      OperationSpec spec,
      Map<String, Object> payload,
      Config config,
      String idempotencyKey,
      Map<String, String> extraHeaders,
      Duration timeout) {
    String path = spec.path;
    List<String[]> query = new ArrayList<String[]>();
    Map<String, String> headers = new LinkedHashMap<String, String>();
    headers.put("accept", "application/json");
    headers.put("user-agent", config.userAgent);
    for (Map.Entry<String, String> entry : extraHeaders.entrySet()) {
      if (!RESERVED_HEADERS.contains(entry.getKey().toLowerCase())) {
        headers.put(entry.getKey().toLowerCase(), entry.getValue());
      }
    }
    Map<String, Object> body = new LinkedHashMap<String, Object>();
    boolean hasBody = false;
    StringBuilder cookie = new StringBuilder();

    for (OperationSpec.Param param : spec.params) {
      Object value = payload.get(param.key);
      if (value == null) {
        continue;
      }
      if ("path".equals(param.in)) {
        path = path.replace("{" + param.wireName + "}", encodePath(scalar(value)));
      } else if ("query".equals(param.in)) {
        query.add(new String[] {param.wireName, scalar(value)});
      } else if ("header".equals(param.in)) {
        headers.put(param.wireName, scalar(value));
      } else if ("cookie".equals(param.in)) {
        if (cookie.length() > 0) {
          cookie.append("; ");
        }
        cookie.append(param.wireName).append('=').append(scalar(value));
      } else if ("body".equals(param.in)) {
        body.put(param.wireName, value);
        hasBody = true;
      }
    }

    Object bodyValue = hasBody ? body : null;
    if (spec.body != null) {
      if ("fields".equals(spec.body.projection)) {
        for (OperationSpec.BodyField field : spec.body.fields) {
          Object value = payload.get(field.key);
          if (value == null) {
            continue;
          }
          body.put(field.wireName, value);
          hasBody = true;
        }
        if (hasBody) {
          bodyValue = body;
        }
      } else if (payload.get("body") != null) {
        bodyValue = payload.get("body");
        hasBody = true;
      }
    }

    if (spec.idempotency.carrier != null && idempotencyKey != null && !idempotencyKey.isEmpty()) {
      OperationSpec.Carrier carrier = spec.idempotency.carrier;
      if ("header".equals(carrier.mechanism)) {
        // HTTP field names are case-insensitive; drop any modeled spelling
        // before injecting the one authoritative safety value.
        Iterator<String> names = headers.keySet().iterator();
        while (names.hasNext()) {
          if (names.next().equalsIgnoreCase(carrier.key)) {
            names.remove();
          }
        }
        headers.put(carrier.key, idempotencyKey);
      } else if ("query".equals(carrier.mechanism)) {
        query.removeIf(pair -> pair[0].equals(carrier.key));
        query.add(new String[] {carrier.key, idempotencyKey});
      } else if ("path".equals(carrier.mechanism)) {
        path = path.replace("{" + carrier.key + "}", encodePath(idempotencyKey));
      } else if ("body".equals(carrier.mechanism)) {
        List<String> carrierPath =
            carrier.path.isEmpty() ? Arrays.asList(carrier.key) : carrier.path;
        bodyValue = setBodyCarrier(bodyValue, carrierPath, idempotencyKey);
        hasBody = true;
      }
    }

    // A delegated token source takes priority over a static token: it is how
    // a caller plugs in a refreshed authorization-code grant without the SDK
    // ever holding a long-lived secret of its own. Resolved once per call,
    // never cached here — a supplier that wants caching does its own.
    String resolvedToken = config.tokenSupplier != null ? config.tokenSupplier.get() : config.token;
    if (resolvedToken != null && !resolvedToken.isEmpty() && config.authName != null) {
      if ("header".equals(config.authIn)) {
        String value =
            config.authScheme == null || config.authScheme.isEmpty()
                ? resolvedToken
                : config.authScheme + " " + resolvedToken;
        headers.put(config.authName.toLowerCase(), value);
      } else {
        query.add(new String[] {config.authName, resolvedToken});
      }
    }
    if (cookie.length() > 0) {
      headers.put("cookie", cookie.toString());
    }

    StringBuilder target = new StringBuilder();
    String base = config.baseUrl;
    while (base.endsWith("/")) {
      base = base.substring(0, base.length() - 1);
    }

    // A GraphQL service serves one endpoint; the field name travels in the
    // document, never in the URL.
    if ("graphql".equals(spec.wireProtocol) && spec.graphql != null) {
      java.util.Map<String, Object> gqlPayload = new java.util.LinkedHashMap<String, Object>();
      gqlPayload.put("query", spec.graphql.document);
      gqlPayload.put("operationName", spec.graphql.operationName);
      gqlPayload.put(
          "variables",
          bodyValue instanceof java.util.Map ? bodyValue : new java.util.LinkedHashMap<String, Object>());
      headers.put("content-type", "application/json");
      headers.put("accept", "application/json");
      String gqlBody = Json.write(gqlPayload);
      HttpRequest.Builder gqlBuilder =
          HttpRequest.newBuilder(URI.create(base))
              .timeout(timeout)
              .method("POST", HttpRequest.BodyPublishers.ofString(gqlBody));
      for (Map.Entry<String, String> entry : headers.entrySet()) {
        gqlBuilder.header(entry.getKey(), entry.getValue());
      }
      return new Built(gqlBuilder.build(), gqlBody);
    }

    // A SOAP service serves one endpoint. The path is a coordinate Anvil
    // synthesized to hold operations apart in a path-keyed model, so it is
    // deliberately dropped: the address is the base URL, from soap:address.
    if ("soap".equals(spec.wireProtocol) && spec.soap != null) {
      headers.putAll(soapHeaders(spec.soap));
      headers.put("accept", spec.soap.contentType.split(";")[0]);
      String envelope = buildEnvelope(spec.soap, bodyValue);
      HttpRequest.Builder soapBuilder =
          HttpRequest.newBuilder(URI.create(base))
              .timeout(timeout)
              .method("POST", HttpRequest.BodyPublishers.ofString(envelope));
      for (Map.Entry<String, String> entry : headers.entrySet()) {
        soapBuilder.header(entry.getKey(), entry.getValue());
      }
      return new Built(soapBuilder.build(), envelope);
    }

    target.append(base).append(path);
    for (int index = 0; index < query.size(); index++) {
      target.append(index == 0 ? '?' : '&');
      target
          .append(encodeQuery(query.get(index)[0]))
          .append('=')
          .append(encodeQuery(query.get(index)[1]));
    }

    HttpRequest.BodyPublisher publisher = HttpRequest.BodyPublishers.noBody();
    String bodyText = null;
    if (hasBody) {
      headers.put(
          "content-type",
          spec.body == null || spec.body.contentType.isEmpty()
              ? "application/json"
              : spec.body.contentType);
      bodyText = Json.write(bodyValue);
      publisher = HttpRequest.BodyPublishers.ofString(bodyText);
    }
    HttpRequest.Builder builder =
        HttpRequest.newBuilder(URI.create(target.toString()))
            .timeout(timeout)
            .method(spec.httpMethod, publisher);
    for (Map.Entry<String, String> entry : headers.entrySet()) {
      builder.header(entry.getKey(), entry.getValue());
    }
    return new Built(builder.build(), bodyText);
  }

  /**
   * Run one operation end to end: gate, build, send, and retry only where the
   * contract proves retrying is safe.
   */
  static Object invoke(
      Config config, OperationSpec spec, Map<String, Object> rawPayload, CallOptions options) {
    assertWireExecutable(spec, config);
    assertConfirmed(spec, options);
    Map<String, Object> payload = new LinkedHashMap<String, Object>();
    for (Map.Entry<String, Object> entry : rawPayload.entrySet()) {
      if (entry.getValue() != null) {
        payload.put(entry.getKey(), entry.getValue());
      }
    }
    String idempotencyKey = Safety.resolveIdempotencyKey(spec, options.idempotencyKey(), payload);
    assertKeyed(spec, idempotencyKey);

    boolean keyed = idempotencyKey != null && !idempotencyKey.isEmpty();
    boolean safeToRetry = Safety.retryIsSafe(spec, keyed);
    Duration timeout = options.timeout() == null ? config.timeout : options.timeout();
    if (options.dryRun()) {
      // Every gate above has run; nothing below is sent. A dry run never
      // resolves a credential, exactly as the runtime's own dry run does not.
      Invoker.Config preview = DryRun.withoutCredential(config);
      return DryRun.plan(
          spec,
          buildRequest(spec, payload, preview, idempotencyKey, options.headers(), timeout),
          keyed,
          safeToRetry);
    }
    int maxAttempts = safeToRetry ? spec.retry.maxAttempts : 1;
    HttpRequest request =
        buildRequest(spec, payload, config, idempotencyKey, options.headers(), timeout).request;
    String trace = traceId();

    for (int attempt = 1; ; attempt++) {
      HttpResponse<String> response = null;
      try {
        response = config.httpClient.send(request, HttpResponse.BodyHandlers.ofString());
      } catch (IOException | InterruptedException failure) {
        if (failure instanceof InterruptedException) {
          Thread.currentThread().interrupt();
        }
        // Never surface the transport's own message: it can carry the URL, and
        // the URL can carry a query-carried credential.
        AnvilException error =
            AnvilException.builder(
                    "upstream_unavailable",
                    spec.id,
                    spec.id + " failed: the request could not reach the upstream.")
                .traceId(trace)
                .retryable(spec.retry.retryTransport)
                .safeToRetry(safeToRetry)
                .build();
        if (!safeToRetry || !spec.retry.retryTransport || attempt >= maxAttempts) {
          throw error;
        }
        Safety.RetryDecision decision =
            Safety.resolveRetryDelay(attempt, spec.retry, -1L, config.random.getAsDouble());
        if (decision.stop || !sleep(decision.delayMs)) {
          throw error;
        }
        continue;
      }

      int status = response.statusCode();
      // GraphQL reports failures inside a 200 with an errors array — the same
      // danger as a SOAP fault. A partial response counts as a failure.
      if ("graphql".equals(spec.wireProtocol) && spec.graphql != null) {
        Object parsed = Json.parse(response.body());
        java.util.Map<String, Object> envelope =
            parsed instanceof java.util.Map
                ? castMap(parsed)
                : new java.util.LinkedHashMap<String, Object>();
        Object rawErrors = envelope.get("errors");
        if (rawErrors instanceof java.util.List && !((java.util.List<?>) rawErrors).isEmpty()) {
          Object first = ((java.util.List<?>) rawErrors).get(0);
          String message = "the service returned a GraphQL error";
          if (first instanceof java.util.Map) {
            Object candidate = castMap(first).get("message");
            if (candidate instanceof String && !((String) candidate).isEmpty()) {
              message = (String) candidate;
            }
          }
          throw AnvilException.builder(
                  "unknown_upstream_error", spec.id, spec.id + " failed upstream: " + message)
              .traceId(trace)
              .safeToRetry(safeToRetry)
              .build();
        }
        if (status >= 200 && status < 300) {
          Object data = envelope.get("data");
          if (data instanceof java.util.Map) {
            java.util.Map<String, Object> fields = castMap(data);
            if (fields.containsKey(spec.graphql.rootField)) {
              return fields.get(spec.graphql.rootField);
            }
          }
          return data;
        }
      }

      // A soap:Fault is a failure the transport delivered successfully, and
      // servers send it with 200 as readily as 500 — so the status is not the
      // answer here, the envelope is. Read before the status branch, or a
      // faulted 200 would be returned to the caller as a result.
      if ("soap".equals(spec.wireProtocol) && spec.soap != null) {
        SoapFault fault = soapFaultIn(response.body());
        if (fault != null) {
          // Only a Server fault is transient. A Client fault will fail
          // identically on retry, and retrying a mutation on one is exactly
          // what the safety contract forbids.
          if (fault.retryable && safeToRetry && attempt < maxAttempts) {
            Safety.RetryDecision decision =
                Safety.resolveRetryDelay(attempt, spec.retry, -1L, config.random.getAsDouble());
            if (!decision.stop && sleep(decision.delayMs)) {
              continue;
            }
          }
          throw AnvilException.builder(
                  "unknown_upstream_error", spec.id, spec.id + " failed upstream: " + fault.message)
              .traceId(trace)
              .retryable(fault.retryable)
              .safeToRetry(safeToRetry)
              .build();
        }
        if (status >= 200 && status < 300) {
          return decodeEnvelope(spec.soap, response.body());
        }
      }

      if (status >= 200 && status < 300) {
        return Json.parse(response.body());
      }

      String code = AnvilException.httpStatusToErrorCode(status);
      Optional<String> retryAfterHeader = response.headers().firstValue("retry-after");
      long retryAfterMs =
          retryAfterHeader.isPresent()
              ? Safety.parseRetryAfter(retryAfterHeader.get(), Instant.now())
              : -1L;
      AnvilException.Builder failure =
          AnvilException.builder(
                  code, spec.id, spec.id + " failed upstream with HTTP " + status + ".")
              .traceId(trace)
              .retryable(AnvilException.isRetryableCode(code))
              .safeToRetry(safeToRetry)
              .upstream(status, response.headers().firstValue("x-request-id").orElse(null));
      if (retryAfterMs >= 0) {
        failure.retryAfterMs(retryAfterMs);
      }
      if (!spec.retry.retries(status) || attempt >= maxAttempts) {
        throw failure.build();
      }
      if (!safeToRetry) {
        // A transient failure we are not allowed to repeat. Say exactly that,
        // rather than retrying a write whose duplicate we cannot rule out.
        AnvilException.Builder blocked =
            AnvilException.builder(
                    "unsafe_retry_blocked",
                    spec.id,
                    spec.id
                        + " failed transiently (HTTP "
                        + status
                        + ") but is not provably idempotent, so it was not retried. Retry"
                        + " deliberately with an idempotency key if the effect is safe to repeat.")
                .traceId(trace)
                .upstream(status, null);
        if (retryAfterMs >= 0) {
          blocked.retryAfterMs(retryAfterMs);
        }
        throw blocked.build();
      }
      Safety.RetryDecision decision =
          Safety.resolveRetryDelay(attempt, spec.retry, retryAfterMs, config.random.getAsDouble());
      if (decision.stop) {
        throw AnvilException.builder(
                code,
                spec.id,
                spec.id
                    + " asked to be retried in "
                    + decision.delayMs
                    + "ms, longer than this client will wait inside one call. Retry deliberately"
                    + " after that delay.")
            .traceId(trace)
            .retryable(true)
            .safeToRetry(safeToRetry)
            .retryAfterMs(decision.delayMs)
            .build();
      }
      if (!sleep(decision.delayMs)) {
        throw failure.build();
      }
    }
  }

  private static boolean sleep(long delayMs) {
    if (delayMs <= 0) {
      return true;
    }
    try {
      Thread.sleep(delayMs);
      return true;
    } catch (InterruptedException interrupted) {
      Thread.currentThread().interrupt();
      return false;
    }
  }

  /**
   * Read one named field off a decoded response. Async contracts name their
   * handle and state fields exactly; this reads that name and nothing else,
   * rather than guessing at a shape the contract never promised.
   */
  @SuppressWarnings("unchecked")
  static Object field(Object value, String name) {
    return value instanceof Map ? ((Map<String, Object>) value).get(name) : null;
  }
}
`;
}
