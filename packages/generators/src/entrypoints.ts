import type { AirDocument } from "@anvil/air";
import { resolveAsyncContract } from "@anvil/air";
import {
  SERVE_BUNDLE,
  SERVE_BUNDLE_SHA256,
  SERVE_BUNDLE_VERSION,
} from "@anvil/mcp-runtime/serve-bundle";

/**
 * The `/webhooks/<service>/<opId>` routes the generated Cloud Run entrypoint
 * serves (design doc `docs/design/async-events-and-callbacks.md` §7/§14):
 * one route per operation whose `AsyncContract` resolved a real webhook
 * (`contract.webhook` present, `webhookOperation` present). `<opId>` names
 * the compiled webhook-receiver operation itself (the thing
 * `handleWebhook()`'s `operation` param wants), not the submitting operation
 * — a receiver route answers "which inbound shape is this", and that is the
 * webhook operation's identity, not the mutation that happens to be waiting
 * on it. Computed once at generation time so the generated route table is a
 * pure function of AIR, exactly like every other generated artifact.
 */
export interface WebhookRoute {
  path: string;
  submitOperationId: string;
  webhookOperationId: string;
}

export function resolvedWebhookRoutes(air: AirDocument): WebhookRoute[] {
  const allOpsById = new Map(air.operations.map((op) => [op.id, op]));
  const routes: WebhookRoute[] = [];
  const seenPaths = new Set<string>();
  for (const op of air.operations) {
    if (op.state !== "approved") continue;
    const resolution = resolveAsyncContract(op, allOpsById);
    if (!resolution.ok || !resolution.contract.webhook || !resolution.webhookOperation) continue;
    const path = `/webhooks/${encodeURIComponent(air.service.id)}/${encodeURIComponent(resolution.webhookOperation.id)}`;
    // Two submitting operations sharing one webhook operation would collide
    // on the same inbound route; keep the first resolved and skip the rest
    // rather than serving two different route-table entries under one path.
    if (seenPaths.has(path)) continue;
    seenPaths.add(path);
    routes.push({
      path,
      submitOperationId: op.id,
      webhookOperationId: resolution.webhookOperation.id,
    });
  }
  return routes;
}

/**
 * The generated per-service CLI entrypoint. It embeds AIR and dispatches through
 * the shared `runToolCli` engine in @anvil/cli, so the CLI, MCP, and skill never
 * drift: one engine, one model, three surfaces.
 */
export function generateCliSource(air: AirDocument): string {
  return `#!/usr/bin/env node
// Generated by Anvil — type-safe CLI for "${air.service.id}".
// The most important progressive-disclosure interface: --help, --schema,
// --examples, --explain, --dry-run, discover, inspect-risk (spec §7).
import { readFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { runToolCli } from "@anvil/cli";
import { loadAirDocument } from "@anvil/air";

const air = loadAirDocument(
  JSON.parse(readFileSync(fileURLToPath(new URL("./air.json", import.meta.url)), "utf8")),
);
// The sibling local MCP server, for \`--mcp stdio\` (skill → CLI → MCP). The CLI
// lives at cli/${air.service.id}.mjs, so its stdio server is ../mcp/server.js.
const mcpServerPath = fileURLToPath(new URL("../mcp/server.js", import.meta.url));
process.exitCode = await runToolCli(air, process.argv.slice(2), { mcpServerPath });
`;
}

/**
 * The deployable runtime server, prebuilt at Anvil's own build.
 *
 * This is `@anvil/mcp-runtime`'s `dist/serve.js` — one self-contained file that
 * serves any service from the data beside it — as text. A compile COPIES it into
 * the bundle; nothing is bundled at compile time. It used to be a 700-line
 * template string here, re-bundled with esbuild on every `anvil compile`, which
 * put a bundler on the hot path, shipped esbuild's native binary in the CLI, and
 * required Anvil's own packages to be resolvable from a real `node_modules` at
 * compile time — the one thing a single-file distribution cannot offer. The two
 * values that made the template per-service (the webhook route table, whether a
 * durable ledger is required) are now data the server derives or reads at boot.
 *
 * Imported as a plain module rather than read from disk so the artifact travels
 * with the generator through any packer without a filesystem lookup.
 */
export function runtimeServerBundle(): string {
  return SERVE_BUNDLE;
}

/**
 * The route table the runtime reads at boot as `webhooks.json` — exactly
 * `resolvedWebhookRoutes`' output, serialized. Part of the hashed artifact:
 * `deploymentArtifactHash` covers every file under `deploy/runtime/`, and the
 * server refuses to boot without it rather than serving an empty route table.
 */
export function webhookRoutesJson(air: AirDocument): string {
  return `${JSON.stringify(resolvedWebhookRoutes(air), null, 2)}\n`;
}

/**
 * Provenance for the runtime a bundle carries: which `@anvil/mcp-runtime`
 * built it and the sha256 of the exact bytes. Before the prebuild, a bundle's
 * `server.js` depended on the compiling Anvil's installed packages implicitly
 * and afresh on every run; now the dependence is the same but fixed and
 * stamped, so a reviewer or a certification check can say "this bundle's
 * runtime is the one its Anvil shipped" instead of inferring it.
 */
export function runtimeLockJson(): string {
  return `${JSON.stringify(
    { schemaVersion: 1, anvilVersion: SERVE_BUNDLE_VERSION, runtimeDigest: SERVE_BUNDLE_SHA256 },
    null,
    2,
  )}\n`;
}
